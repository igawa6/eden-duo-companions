// Writes the offline text-fit tables tools/pokemon-sword/<lang>_font_metrics.json: the advances of
// every BMP code point of a module font chain at the module's raster cap height, computed by the
// module's own code (sw_modfont Face == the atlas builder). Numbers only: no outlines or pixels
// leave the player's romfs / firmware.
//   Japanese (the game's FOT-RodinNTLGPro-DB face):
//     sw-font-metrics-tool <romfs>/bin/font/FOT-RodinNTLGPro-DB.BFOTF tools/pokemon-sword/ja_font_metrics.json
//   Korean / Chinese (the console's shared fonts, decrypted TrueType as the runtime's "sysfont:"
//   source returns them, in the module's chain order, then the Rodin face last):
//     sw-font-metrics-tool --chain tools/pokemon-sword/ko_font_metrics.json <name> \
//         nintendo_udsg-r_ko_003.ttf <romfs>/bin/font/FOT-RodinNTLGPro-DB.BFOTF
#include <cstdio>
#include <cstring>
#include <fstream>
#include <iterator>
#include <memory>
#include <string>
#include <vector>

#include "sw_modfont.h"

namespace {
std::vector<std::uint8_t> ReadFile(const char* path) {
    std::ifstream in(path, std::ios::binary);
    return {std::istreambuf_iterator<char>(in), {}};
}
// A .BFOTF is decoded (the game's container); anything else is taken as plain TrueType/OpenType.
std::shared_ptr<const std::vector<std::uint8_t>> Load(const char* path) {
    auto file = ReadFile(path);
    const std::string p = path;
    if (p.size() > 6 && p.compare(p.size() - 6, 6, ".BFOTF") == 0) {
        auto otf = sw_modfont::DecodeBfotf(file);
        if (!otf) return nullptr;
        file = std::move(*otf);
    }
    return file.size() >= 12 ? std::make_shared<const std::vector<std::uint8_t>>(std::move(file)) : nullptr;
}
} // namespace

int main(int argc, char** argv) {
    const bool chain = argc >= 5 && std::strcmp(argv[1], "--chain") == 0;
    if (!chain && argc != 3) {
        std::fprintf(stderr,
                     "usage: %s <FOT-RodinNTLGPro-DB.BFOTF> <out.json>\n"
                     "       %s --chain <out.json> <description> <font>... (priority order)\n",
                     argv[0], argv[0]);
        return 2;
    }
    std::vector<sw_modfont::Face::Bytes> fonts;
    for (int i = chain ? 4 : 1; i < (chain ? argc : 2); ++i) {
        auto f = Load(argv[i]);
        if (!f) {
            std::fprintf(stderr, "not a font: %s\n", argv[i]);
            return 1;
        }
        fonts.push_back(std::move(f));
    }
    sw_modfont::Face face;
    if (!face.Open(std::move(fonts), sw_modfont::kCapPx)) {
        std::fprintf(stderr, "cannot open the face chain\n");
        return 1;
    }
    const char* out_path = chain ? argv[2] : argv[2];
    std::FILE* out = std::fopen(out_path, "w");
    if (!out) return 1;
    if (chain)
        std::fprintf(out, "{\n \"_note\": \"Generated by native/modules/sw_modfont_tool.cpp --chain from %s (the module's face chain for this language): advance in atlas px at cap px (the runtime scales by scale*5/cap), per code point (hex). Numbers only. Do not edit.\",\n",
                     argv[3]);
    else
        std::fprintf(out, "{\n \"_note\": \"Generated by native/modules/sw_modfont_tool.cpp from romfs:/bin/font/FOT-RodinNTLGPro-DB.BFOTF (the Japanese companion font): advance in atlas px at cap px (the runtime scales by scale*5/cap), per code point (hex). Numbers only. Do not edit.\",\n");
    std::fprintf(out, " \"cap\": %u,\n \"advances\": {", face.cap());
    bool first = true;
    int n = 0;
    for (char32_t cp = 0x20; cp <= 0xFFFF; ++cp) {
        if (cp >= 0xD800 && cp <= 0xDFFF) continue;
        const int a = face.Advance(cp);
        if (a < 0) continue;
        std::fprintf(out, "%s\n  \"%04X\": %d", first ? "" : ",", static_cast<unsigned>(cp), a);
        first = false;
        ++n;
    }
    std::fprintf(out, "\n }\n}\n");
    std::fclose(out);
    std::printf("%d code points, cap %u\n", n, face.cap());
    return 0;
}

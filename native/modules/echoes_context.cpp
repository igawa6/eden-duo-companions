bool At(uint64_t a, uint64_t b, uint64_t &out) {
  if (a > std::numeric_limits<uint64_t>::max() - b)
    return false;
  out = a + b;
  return true;
}
bool Bytes(const ReadFn &r, uint64_t a, void *p, size_t n) {
  return a && n <= std::numeric_limits<uint64_t>::max() - a && r(a, p, n);
}
uint64_t LE(const uint8_t *p) {
  uint64_t v = 0;
  for (unsigned i = 0; i < 8; ++i)
    v |= uint64_t(p[i]) << (i * 8);
  return v;
}
bool Q(const ReadFn &r, uint64_t a, uint64_t &v) {
  std::array<uint8_t, 8> b{};
  if (a % 8 || !Bytes(r, a, b.data(), 8))
    return false;
  v = LE(b.data());
  return true;
}

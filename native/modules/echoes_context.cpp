    if(message->owner<8)return false;
    o.primary=message->owner-8;
    if(!Q(r,o.primary,value)||!At(base,0x3416d28,expected)||value!=expected||
       !At(base,0x3416d28+0x20,at)||!Q(r,at,value)||!At(base,0x2539630,expected)||value!=expected)return false;
    std::array<uint8_t,4> index{};std::array<uint8_t,24> vector{};

struct InventorySource {
  uint64_t owner{}, state{};
  bool operator==(const InventorySource&) const = default;
};
struct InventorySnapshot {
  bool compatible{}, native_predicate_supported{}, inventory_valid{};
  InventorySource source{};
  uint32_t acquired_accessories{};
  uint16_t acquired_outfits{}, equipped_outfit{};
  uint8_t accessory_capacity{}, equipped_accessory_count{};
  std::array<uint32_t, MaxAccessorySlots> equipped_accessories{};
  std::array<uint8_t, IngredientKinds> ingredients{};
  uint8_t coupons{};
};
struct RupeeSnapshot {
  bool compatible{}, native_predicate_supported{}, rupees_valid{};
  InventorySource source{};
  uint32_t rupees{};
};
// Independent of gear ownership/consumable validation; invalid or torn samples
// return no counter/source. The caller still gates UI through native context.
RupeeSnapshot ReadRupees(const ReadFn& read, uint64_t main_base,
                        bool build_matches);
// A stable inventory does not establish ordinary gameplay or authorize actions.
// The caller must gate presentation with independently verified context. Exact
// original owner type and a conservative, uncontended subset of the native
// reference-acquisition preconditions are required. No guest calls, writes,
// locks or reference-counter changes. Every failure returns cleared payload.
InventorySnapshot ReadInventory(const ReadFn& read, uint64_t main_base,
                                bool build_matches);

#pragma once

// Fire Emblem: Three Houses (010055D009F78000): the companion's fixed words in the game's language.
//
// The manifest's `label` widgets bind "ui.l.<key>" (bind_text) instead of carrying English; the
// module publishes the text for the game's language under those keys. Two sources:
//   - a game term (a stat, a weapon skill, "Victory Conditions" ...) is read from the game's own
//     message data at run time in the game's language (fe3h_text.h: part, index), so no game
//     text ships and the wording is the game's;
//   - a phrase the game has no word for is this companion's own text, one per column below
//     (English = the fallback of everything).
// The table is fe3h_labels_data.inc, generated by tools/fe3h-labels/gen_labels.py from the labels
// the manifest binds. The language comes from fe3h_language.h.

#include <cstddef>
#include <string>

namespace fe3h_labels {

// Own-text columns. The game's 12 languages share nine of them (msgdata order: 0 JPN, 1 ENG_U,
// 2 ENG_E, 3 GER, 4 FRA_E, 5 FRA_U, 6 ESP_E, 7 ESP_U, 8 ITA, 9 KOR, 10 TWN, 11 CHN).
enum Column : int { En, Ja, De, Fr, Es, It, Ko, Twn, Chn, ColumnCount };

struct Entry {
    const char* key;              // published as "ui.l." + key
    int part;                     // game text part (fe3h_text.h), -1 = none
    int index;                    // game text index in that part
    const char* own[ColumnCount]; // nullptr = use En
};

// The table (generated) and its size.
const Entry* Entries();
size_t EntryCount();

// Column of a game language index; English for an unknown (negative / out of range) one.
Column ColumnOf(int language);

// The text of `entry` in `language` without the game's text (own column, else English).
const char* Own(const Entry& entry, int language);

// A game text made fit for a label: the control codes (< 0x20) removed.
std::string CleanGameText(const std::string& text);

} // namespace fe3h_labels

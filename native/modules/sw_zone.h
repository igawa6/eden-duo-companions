// Current-zone place-name decode + the Max Raid den-location table.
//
// Zone name: LIVE-READERS-132.md's 2026-10-25 "Raid dens + current-zone live readers" session
// found a live, per-transition-updated UTF-16LE place-name buffer at heap+0x441C1EC8, immediately
// preceded by a stable 8-byte tag at heap+0x441C1EC0 (constant FF FF FF FF 08 00 03 00 every
// capture, consistent with the RE batch's "{hash, name-ptr}"-shaped `View_PlaceName` finding).
// Live-ness was proven in-boot, not just cross-boot: flying Axewell -> Wyndon overwrote the same
// address in place on the same tick (old trailing bytes "...e Axewell" survived past the new
// "Wyndon\0\0" terminator -- a reused mutable buffer, not a fresh allocation or a save-time
// snapshot). DecodeZoneName below validates the 8-byte tag before trusting anything after it
// (MODULE_GUIDE.md "No heuristics": an unrecognised tag means this is not the record we think it
// is, not "decode it anyway"), and bounds the decode to the caller-supplied `len` (never reads
// past what was actually read live) and to kMaxZoneNameChars, stopping at the first UTF-16
// double-null so a shorter new name never trails stale bytes from a longer previous one (the
// exact failure mode seen directly in that session).
//
// Den-zone table: RaidSpawnDetail (sources/RaidSpawnList8.cs) has no species/zone field of its
// own (Hash/Seed/Stars/RandRoll/DenType/Flags only) -- a den's zone is only recoverable via its
// ARRAY INDEX, cross-referenced against a third-party source that ships the identical den order
// with a per-den `Location` field: sources/NestLocations.cs (Leanny/PKHeX_Raid_Plugin, fetched
// 2026-10-25; "this is the order from the raid block" per its own comment) resolved against
// sources/MapRegions.cs's three `AllRegions` zone-name lists (same repo, "Map Util/MapRegions.cs",
// fetched this session) -- `Location` is a GLOBAL index into
// Galar(0-16)+IsleOfArmor(17-31)+CrownTundra(32-43) concatenated in exactly that AllRegions
// order (confirmed directly from both files, not assumed). kZoneRegion/kGalarDenZone/kIoaDenZone/
// kCtDenZone below are generated by tools/decode_dens.py's `--gen-zone-table` mode from those two
// source files -- do not hand-edit, regenerate instead (the script also re-fixes one upstream
// typo, `GiantsCap` -> "Giant's Cap", see its own comment). Cross-checked there against all 24 of
// LIVE-READERS-132.md's own hand-decoded fixture dens (8 active dens x 3 regions): every name
// matches exactly.
//
// Confidence: medium-high overall (the den-zone mapping leans on a third-party community source,
// not independently re-derived from this build's own romfs tables -- same status
// LIVE-READERS-132.md already assigned); the zone-NAME reader itself (DecodeZoneName) is high
// confidence, live-verified 2 independent boots.
//
// Save-time caveat: unlike the zone-name popup, the den tables themselves
// (sw_addresses.h's "dens.vanilla"/"dens.isle_of_armor"/"dens.crown_tundra") are a SAVE-FILE-TIME
// snapshot, not a per-frame live struct (same `0x450C6xxx-0x450C9xxx` cluster this module's own
// party-current-HP gate already proved only refreshes on an explicit in-game Save) -- a page
// showing den data must say so (a small "as of last save" marker), never imply it is live.


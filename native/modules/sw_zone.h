using u8 = std::uint8_t;

// The 8-byte tag immediately preceding the live place-name buffer (heap+0x441C1EC0, size 8).
// Checked byte-for-byte; a mismatch means this is not the {tag, name} record we think it is.
inline constexpr u8 kZoneTag[8] = {0xFF, 0xFF, 0xFF, 0xFF, 0x08, 0x00, 0x03, 0x00};

// Bounded decode capacity -- generous for any real Sword/Shield place name, and matches
// sw_addresses.h's "location.zone_name" anchor read size (8-byte tag + 0x90 bytes of buffer).
inline constexpr std::size_t kMaxZoneNameChars = 48; // 96 bytes of UTF-16LE

/// Validates the 8-byte tag, then decodes up to `len - 8` bytes of UTF-16LE starting right after
/// it as a zone name, stopping at the first UTF-16 double-null (or `kMaxZoneNameChars`,
/// whichever comes first). `raw` must point at >=8 bytes (the tag) followed by the name buffer;
/// `len` is the TOTAL bytes available (tag + name) -- the bound actually read live, not the
/// buffer's nominal on-disk capacity. Fails closed (returns false, leaves `out` untouched) on a
/// tag mismatch, a too-short buffer, a lone UTF-16 surrogate (no real Galar place name needs
/// one; refusing beats guessing at a combine), or an empty decode.
inline bool DecodeZoneName(const u8* raw, std::size_t len, std::string* out) {
    if (!raw || !out) return false;
    if (len < 10) return false; // 8-byte tag + at least one UTF-16 code unit
    if (std::memcmp(raw, kZoneTag, sizeof kZoneTag) != 0) return false;

    const u8* name = raw + 8;
    const std::size_t name_bytes = len - 8;
    std::string decoded;
    std::size_t chars = 0;
    for (std::size_t i = 0; i + 1 < name_bytes && chars < kMaxZoneNameChars; i += 2, ++chars) {
        const unsigned v = static_cast<unsigned>(name[i]) | (static_cast<unsigned>(name[i + 1]) << 8);
        if (v == 0) break; // first double-null terminator
        if (v < 0x80) {
            decoded += static_cast<char>(v);
        } else if (v < 0x800) {
            decoded += static_cast<char>(0xC0 | (v >> 6));
            decoded += static_cast<char>(0x80 | (v & 0x3F));
        } else if (v < 0xD800 || v >= 0xE000) {
            decoded += static_cast<char>(0xE0 | (v >> 12));
            decoded += static_cast<char>(0x80 | ((v >> 6) & 0x3F));
            decoded += static_cast<char>(0x80 | (v & 0x3F));
        } else {
            return false; // surrogate pair -- fail closed, see function comment
        }
    }
    if (decoded.empty()) return false;
    *out = std::move(decoded);
    return true;
}


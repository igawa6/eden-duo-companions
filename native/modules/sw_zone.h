/// Two place names match when they are the same text, except that the game writes ’ (U+2019)
/// where an older table or a typed name has an ASCII apostrophe, and U+202F (French narrow
/// no-break space, which the module's decoder turns into U+00A0) is U+00A0.
inline bool SameZoneName(std::string_view a, std::string_view b) {
    constexpr std::string_view kCurly = "\xE2\x80\x99", kNnbsp = "\xE2\x80\xAF", kNbsp = "\xC2\xA0";
    const auto unit = [&](std::string_view s, std::size_t i, std::size_t& n) -> std::string_view {
        if (s.substr(i, 3) == kCurly) { n = 3; return "'"; }
        if (s.substr(i, 3) == kNnbsp) { n = 3; return kNbsp; }
        if (s.substr(i, 2) == kNbsp) { n = 2; return kNbsp; }
        n = 1;
        return s.substr(i, 1);
    };
    std::size_t i = 0, j = 0;
    while (i < a.size() && j < b.size()) {
        std::size_t na = 0, nb = 0;
        if (unit(a, i, na) != unit(b, j, nb)) return false;
        i += na;
        j += nb;
    }
    return i == a.size() && j == b.size();
}

/// The place_name lines of every language (index = sw_lang::Index), as the Reader loads them.
using PlaceLines = std::array<std::vector<std::string>, sw_lang::kCount>;

/// A zone's Town Map name in one language ("" when that language's table is unreadable).
inline const std::string& ZoneName(const PlaceLines& lines, int zone_id, sw_lang::Lang lang) {
    static const std::string kNone;
    if (zone_id < 0 || zone_id >= 44) return kNone;
    const auto& table = lines[static_cast<std::size_t>(sw_lang::Index(lang))];
    const auto line = static_cast<std::size_t>(kZonePlaceLine[zone_id]);
    return line < table.size() ? table[line] : kNone;
}

/// Exact-text lookup (no fuzzy match -- MODULE_GUIDE.md "No heuristics"): returns the zone's
/// table index (0-43), or -1 if `name` is not a Wild Area / Isle of Armor / Crown Tundra zone
/// (towns, Routes with no den icon, Camp, etc. correctly miss -- callers use that to hide the
/// den strip, not to guess a nearby zone).
/// The live popup name -> zone id. The popup is in the GAME's language (not necessarily the
/// companion's), so the zone's name in every language the player's romfs has matches.
inline int FindZoneId(std::string_view name, const PlaceLines& lines) {
    if (name.empty()) return -1;
    for (int i = 0; i < 44; ++i)
        for (int l = 0; l < sw_lang::kCount; ++l) {
            const auto& zone = ZoneName(lines, i, static_cast<sw_lang::Lang>(l));
            if (!zone.empty() && SameZoneName(name, zone)) return i;
        }
    return -1;
}

enum class DenRegion { kGalar, kIoa, kCt };

/// Returns the global zone id (0-43) for one den slot index within its own region's array, or
/// -1 if `slot` is out of that region's real bounds (100/90/86).
inline int DenSlotZoneId(DenRegion region, int slot) {
    switch (region) {
        case DenRegion::kGalar:
            return (slot >= 0 && slot < 100) ? kGalarDenZone[slot] : -1;
        case DenRegion::kIoa:
            return (slot >= 0 && slot < 90) ? kIoaDenZone[slot] : -1;
        case DenRegion::kCt:
            return (slot >= 0 && slot < 86) ? kCtDenZone[slot] : -1;
    }
    return -1;
}


// Magoland's Kirby draws his eyes with code every Kirby shares (the iris a fixed blue): for a preset with eyes of its own
// the body programs get an eye made of per-Kirby coefficients, eye = alpha * top + iris * (iris - top) + highlight *
// (highlight - top) by channel, read from padding words of BodyC's GPU buffer that the game never writes (YyEyePad +
// 0x10 * (channel * 3 + term)); each Kirby gets them, player 1 his preset's, the others the game's eye.
inline constexpr std::uint32_t YyEyePad = 0x1C;

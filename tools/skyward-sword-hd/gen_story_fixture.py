"""Generate native/modules/sshd_story_table.inc (the native story-flag mapping table) and
native/modules/sshd_story_fixture.inc, the test data of dsmod-sshd-story (the table is also used
by the module tests that fake the story reader's guest).

Inputs are the NPC map mark analysis of 2026-11-11, kept outside this repository: the native
story-flag mapping table (story-table-raw.json: word / shift / width per id, the two bytes the
native getter main+0xB7F8B8 decodes) and the live native snapshots that reader-native-
comparison.json compared (201 map-mark condition readbacks). Per snapshot the
fixture keeps only what the mark condition reads from the save file: the story words
(slot+0x8E4, 255 u16), the current scene's 128 scene flags (slot+0x1A64 + 16 * scene), the temp
flags (slot+0x30F4) and the zone flags (slot+0x30FC, rooms 0..15), and per live MapMark its
+0x190..+0x1AF bytes, its room and the native cached results (+0x1A0 story, +0x1A1 scene,
+0x1A2 final). Each snapshot is named by its save, stage and kind only (e.g. "hero-F000-native").

usage: gen_story_fixture.py --input DIR [--output PATH]   (DIR = the analysis folder holding
       those two files and the snapshots; or set SSHD_NPC_INPUT)
"""
import argparse
import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def hexbytes(b, indent='    ', per=24):
    rows = []
    for i in range(0, len(b), per):
        rows.append(indent + ', '.join(f'0x{x:02X}' for x in b[i:i + per]) + ',')
    return '\n'.join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--input', default=os.environ.get('SSHD_NPC_INPUT'), required='SSHD_NPC_INPUT' not in os.environ)
    ap.add_argument('--output', default=str(ROOT / 'native/modules/sshd_story_fixture.inc'))
    a = ap.parse_args()
    rd = Path(a.input)
    table = json.load(open(rd / 'story-table-raw.json'))
    assert len(table) == 2048
    raw = bytearray()
    for i, e in enumerate(table):
        assert e['flag'] == i and 1 <= e['width'] <= 16 and 0 <= e['shift'] <= 15
        raw += bytes([e['word'], (e['shift'] << 4) | (e['width'] - 1)])
    cmp = json.load(open(rd / 'reader-native-comparison.json'))
    Path(a.output).with_name('sshd_story_table.inc').write_text('\n'.join([
        '// SPDX-FileCopyrightText: Copyright 2026 Eden DSMod fork',
        '// SPDX-License-Identifier: GPL-3.0-or-later',
        '// Generated by tools/skyward-sword-hd/gen_story_fixture.py from the native story-flag mapping',
        '// table of the NPC map mark analysis. Do not edit.', '',
        f'constexpr uint8_t kFxStoryTable[{len(raw)}] = {{', hexbytes(raw), '};', '']))
    out = ['// SPDX-FileCopyrightText: Copyright 2026 Eden DSMod fork',
           '// SPDX-License-Identifier: GPL-3.0-or-later',
           '// Generated by tools/skyward-sword-hd/gen_story_fixture.py from the live native snapshots of the',
           '// NPC map mark analysis. Do not edit.', '']
    snaps = []
    seen = {}
    total = 0
    for si, c in enumerate(cmp):
        d = json.load(open(rd / c['snapshot']))
        slot = bytes.fromhex(d['slot'])
        assert len(slot) == 0x53C0
        scene = d['scene_flag_index']
        words = slot[0x8E4:0x8E4 + 2 * 255]
        srow = slot[0x1A64 + 16 * scene:0x1A64 + 16 * scene + 16]
        temp = slot[0x30F4:0x30FC]
        zone = slot[0x30FC:0x30FC + 128]
        want = {r['address'] for r in c['records']}
        marks = [m for m in d['all'] if m['profile'] == '0x224' and m['addr'] in want]
        assert len(marks) == len(c['records']), c['snapshot']
        mrows = []
        for m in marks:
            f = bytes.fromhex(m['f190'])
            native = {r['address']: r['native'] for r in c['records']}[m['addr']]
            assert bool(f[0x12]) == native
            assert 0 <= m['room'] < 16 or m['room'] == -1, m['room']
            mrows.append('{' + ', '.join(f'0x{x:02X}' for x in f) + f'}}, {m["room"]}')
        total += len(mrows)
        # save-stage-kind, without the capture run's time stamp
        name = re.sub(r'^\d{8}T\d{4}\+\d{4}-g0-npc-conditional-', '', c['snapshot']).replace('-actors.json', '')
        seen[name] = seen.get(name, 0) + 1
        if seen[name] > 1:
            name += f'-{seen[name]}'
        out += [f'// {name}: stage {c["stage"]}, scene {scene}, {len(mrows)} marks',
                f'constexpr uint8_t kFxWords{si}[{len(words)}] = {{', hexbytes(words), '};',
                f'constexpr uint8_t kFxScene{si}[16] = {{', hexbytes(srow), '};',
                f'constexpr uint8_t kFxTemp{si}[8] = {{', hexbytes(temp), '};',
                f'constexpr uint8_t kFxZone{si}[128] = {{', hexbytes(zone), '};',
                f'constexpr FxMark kFxMarks{si}[] = {{']
        out += [f'    {{{r}}},' for r in mrows]
        out += ['};', '']
        snaps.append(f'    {{"{name}", "{c["stage"]}", {scene}, kFxWords{si}, kFxScene{si}, kFxTemp{si}, kFxZone{si}, '
                     f'kFxMarks{si}, {len(mrows)}}},')
    out += ['constexpr FxSnapshot kFxSnapshots[] = {'] + snaps + ['};',
                                                                f'constexpr int kFxReadbacks = {total};', '']
    Path(a.output).write_text('\n'.join(out))
    print(a.output, len(cmp), 'snapshots', total, 'readbacks')


main()

"""Decode the Switch core.udas English item-name MDT into a constant lookup table.

Source: etc/core.udas, archive at 0x420, CORE_MESSAGE_3 word 0x15.
MessageData::getAddr uses a language-block u32 offset and (on Switch) u64
message offsets. Message::getCharCode subtracts 0x80. Glyphs refer to the
native common font atlas; no external item-name list is used.
"""
import argparse
import hashlib
import json
import struct
import tempfile
from pathlib import Path

SOURCE_SHA = 'd3ad83a6bda219af11946431ac264baf795b74dc5ce4f50cb882224561affcba'
GLYPHS = {0: ' ', 24: '(', 25: ')', 163: "'", 181: '×'}
GLYPHS.update(enumerate('0123456789:%&+-/=,.', 3))
GLYPHS.update(enumerate('ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz', 39))


def decode(data):
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA:
        raise ValueError('Unsupported core.udas: rederive the archive and message offsets')
    archive = struct.unpack_from('<I', data, 0x2c)[0]
    table = archive + struct.unpack_from('<I', data, archive + 0x15 * 4)[0]
    block = table + struct.unpack_from('<I', data, table + 8)[0]  # language 1 = English
    count = struct.unpack_from('<I', data, block + 4)[0]
    rows = []
    for item in range(count):
        offset = block + struct.unpack_from('<Q', data, block + 8 + item * 8)[0]
        cursor, text = offset, ''
        while True:
            word = struct.unpack_from('<H', data, cursor)[0]
            cursor += 2
            if word == 1:
                break
            if word >= 0x80:
                text += GLYPHS[word - 0x80]  # unknown glyphs fail generation, never guessed
            elif word not in (0, 8, 14):
                raise ValueError(f'Unexpected item-name control {word:#x}')
        # The native Case prints this one message; no category is appended.
        rows.append(dict(id=item, name=text.strip(), category='', offset=offset))
    return rows


def header(rows):
    lines = ['// SPDX-License-Identifier: GPL-3.0-or-later',
             '// Generated by prepare_item_names.py from etc/core.udas (English MDT).',
             '// Each row cites its absolute source byte offset.', '#pragma once',
             '#include <array>', 'namespace re4 {',
             'struct ItemName { const char* name; const char* category; };',
             f'inline constexpr std::array<ItemName,{len(rows)}> ItemNames{{{{']
    for row in rows:
        lines.append('    {' + json.dumps(row['name'], ensure_ascii=False) + ', ""},' +
                     f' // {row["id"]:#05x} @ {row["offset"]:#08x}')
    lines += ['}};', 'inline const ItemName& NativeItemName(unsigned id) {',
              '    static constexpr ItemName missing{"",""};',
              '    return id<ItemNames.size()?ItemNames[id]:missing;', '}', '}']
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('core', type=Path)
    p.add_argument('--output', type=Path, default=Path(tempfile.gettempdir()) / 're4-test-names/re4_item_names.h')
    a = p.parse_args()
    repository = Path(__file__).resolve().parents[2]
    if a.output.resolve().is_relative_to(repository):
        p.error("generated names must be written outside the repository")
    a.output.parent.mkdir(parents=True, exist_ok=True)
    rows = decode(a.core.read_bytes())
    a.output.write_text(header(rows))
    print(f'Decoded {len(rows)} native English item names')

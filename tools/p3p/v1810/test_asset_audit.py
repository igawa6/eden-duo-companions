#!/usr/bin/env python3
"""Adversarial and inventory checks for the original-v1.8.10 artwork audit."""
from __future__ import annotations

import hashlib
import tempfile
import unittest
from pathlib import Path

from audit_assets import check_candidates, load_inventory, manifest_image_references
from v1810_reference import manifest_bytes
import json


class ArtworkAuditTests(unittest.TestCase):
    def test_complete_inventory_and_original_static_manifest_refs(self) -> None:
        rows = load_inventory()
        self.assertEqual(len(rows), 62)
        self.assertEqual(len({Path(n).name for n in rows}), 62)
        self.assertEqual(len(manifest_image_references(json.loads(manifest_bytes()))), 60)

    def test_valid_subset_is_accepted(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            f = Path(temp) / "synthetic.png"
            contents = b"SYNTHETIC TEST ONLY"
            f.write_bytes(contents)
            inventory = {"dualscreen/img/synthetic.png": {
                "sha256": hashlib.sha256(contents).hexdigest(),
                "size_bytes": str(len(contents)),
            }}
            self.assertEqual(check_candidates(Path(temp), inventory), {"synthetic.png"})

    def test_invalid_first_candidate_still_detects_duplicate(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            for folder in ("a", "b"):
                d = root / folder
                d.mkdir()
                (d / "synthetic.png").write_bytes(b"WRONG GRAPHIC")
            inventory = {"dualscreen/img/synthetic.png": {
                "sha256": hashlib.sha256(b"VALID").hexdigest(),
                "size_bytes": str(len(b"VALID")),
            }}
            with self.assertRaisesRegex(ValueError, "Duplicate candidate PNG basename"):
                check_candidates(root, inventory)

    def test_unrecognized_name_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            (Path(temp) / "unknown.png").write_bytes(b"not a PNG")
            with self.assertRaisesRegex(ValueError, "Unrecognized candidate PNG"):
                check_candidates(Path(temp), {})

    def test_integrity_mismatch_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / "synthetic.png"
            path.write_bytes(b"WRONG")
            inventory = {"dualscreen/img/synthetic.png": {
                "sha256": hashlib.sha256(b"RIGHT").hexdigest(),
                "size_bytes": str(len(b"RIGHT")),
            }}
            with self.assertRaisesRegex(ValueError, "regenerated bytes differ"):
                check_candidates(Path(temp), inventory)


if __name__ == "__main__":
    unittest.main()

#!/usr/bin/env python3
"""Compare the 31 historical procedural PNGs with v1.8.10's audited hashes."""
from __future__ import annotations
import argparse
import csv
import hashlib
from pathlib import Path


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory',type=Path,help='directory generated by generate_art_v18_partial.py')
    args=parser.parse_args()
    inventory=Path(__file__).with_name('ASSET_PROVENANCE.csv')
    with inventory.open(newline='',encoding='utf-8') as handle:
        rows=list(csv.DictReader(handle))
    expected={Path(row['asset']).name:row['sha256'] for row in rows if row['origin'].startswith('Matches local 1.8.0')}
    assert len(expected)==31, f'Expected 31 historically reproducible assets, got {len(expected)}'
    present={f.name for f in args.directory.glob('*.png')}
    assert present==set(expected), f'Asset inventory mismatch; missing {set(expected)-present}, unexpected {present-set(expected)}'
    for name,checksum in expected.items():
        actual=hashlib.sha256((args.directory/name).read_bytes()).hexdigest()
        assert actual==checksum, f'{name} differs: {actual}'
    print('All 31 historical v1.8 procedural PNG assets exactly match final v1.8.10 SHA-256 checksums.')

if __name__=='__main__':
    main()

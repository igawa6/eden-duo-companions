def calendar_layout(p):
    """Match the six-row v1.8.10 grid, keeping all 42 live day states.

    This moves *existing* today/holiday/present labels and moon symbols,
    including the sixth week; it never invents calendar data.
    """
    seen = {'prev': 0, 'next': 0, 'days': set()}
    for w in p['widgets']:
        action = w.get('on_tap', '')
        r = w.get('rect', [])
        if action in ('calendar.prev', 'calendar.next'):
            seen[action.rsplit('.', 1)[1]] += 1
            w['rect'] = [r[0], 98, 220, 84]
            w['text_center_h'] = 84

        if (w.get('type') == 'image'
                and w.get('src') == 'module:p3p:fill'
                and r in ([36, 104, 220, 72], [1004, 104, 220, 72])
                and w.get('need_bind') == 'cal.ready'):
            w['rect'] = [r[0], 98, 220, 84]

        binds = [w.get(k, '') for k in ('bind_text', 'need_bind')]
        day_keys = [b for b in binds if b.startswith('cal.')
                    and len(b.split('.')) == 3
                    and b.split('.')[1].isdigit()]
        if not day_keys:
            continue
        n = int(day_keys[0].split('.')[1])
        if not 0 <= n < 42 or len(r) != 4:
            continue
        row = n // 7
        seen['days'].add(n)
        if r[1] == 228 + 114 * row and r[3] == 106:
            w['rect'] = [r[0], 228 + 100 * row, r[2], 91]
        elif r[1] == 238 + 114 * row and r[3] == 44:
            w['rect'] = [r[0], 238 + 100 * row, r[2], 44]
        elif (r[1] == 284 + 114 * row and r[3] == 44
              and w.get('need_bind') == f'cal.{n}.full'):
            w['rect'] = [r[0], 274 + 100 * row, r[2], 36]
            if w.get('src') == 'module:p3p:spr/555@44':
                w['src'] = 'module:p3p:spr/555@36'

    assert seen['prev'] == seen['next'] == 1
    assert seen['days'] == set(range(42)), 'Calendar must preserve six weeks'


def map_layout(p):
    """Frame the live map without changing its tile/marker geometry or binds."""
    widgets = []
    frame = 0
    for w in p['widgets']:
        if w.get('bind_text') == 'map.floor':
            w.update(rect=[420, 18, 600, 48], fit_text=True,
                     wrap_width=600, text_min_scale=4, max_lines=1)
        if (w.get('type') == 'image'
                and w.get('src') == 'module:p3p:fill'
                and w.get('need_bind') == 'map.ready'
                and w.get('rect') == [180, 96, 880, 880]):
            frame += 1
            widgets += by_route(
                lambda accent: shape([172, 88, 896, 896], accent,
                                     need_bind='map.ready'))
        widgets.append(w)
    assert frame == 1, 'Unexpected map background geometry'
    p['widgets'] = widgets


def talk_layout(p):
    """Style dialogue choices without altering directional button gating."""
    widgets = []
    rows = set()
    for w in p['widgets']:
        bind = w.get('bind_text', '')
        if bind == 'talk.text':
            w.update(fit_text=True, wrap_width=1100,
                     text_min_scale=4, max_lines=4)
        if bind.startswith('choice.') and bind.endswith('.text'):
            w.update(fit_text=True, wrap_width=1100,
                     text_min_scale=4, max_lines=2)
        widgets.append(w)

        need = w.get('need_bind', '')
        if (w.get('type') == 'image'
                and w.get('src') == 'module:p3p:fill'
                and need.startswith('choice.')
                and need.endswith('.selected')):
            parts = need.split('.')
            if len(parts) == 3 and parts[1].isdigit():
                n = int(parts[1])
                if 0 <= n < 5:
                    rows.add(n)
                    widgets += by_route(
                        lambda accent, i=n: shape(
                            [36, 430 + 108 * i, 12, 96], accent,
                            need_bind=f'choice.{i}.present'))
    assert rows == set(range(5)), 'Unexpected dialogue choice rows'
    p['widgets'] = widgets

def normalize_other_pages(p):
    page_id = p['id']
    rules = READABILITY.get(page_id, {})
    for w in p['widgets']:
        if w.get('type') != 'label':
            if w.get('type') == 'button' and w.get('text') == 'Back':
                w['text_scale'] = 6
            continue

        bind = w.get('bind_text', '')
        if bind in rules:
            w.update(rules[bind])

        if bind == 'live.date':
            w['text_scale'] = 5

        # The longer strings are game-driven; fixed-size labels clip them.
        # Keep their text in the existing visual lane, with a safe lower scale.
        dynamic = (
            bind.endswith(('.name', '.help', '.partner', '.people'))
            or bind in rules
            or bind.startswith('choice.') and bind.endswith('.text')
        )
        rect = w.get('rect', [0, 0, 0, 0])
        if dynamic and rect[2] > 0:
            w['fit_text'] = True
            w['wrap_width'] = rect[2]
            w.setdefault('text_min_scale', 3)
            w.setdefault('max_lines', 1)

    if page_id == 'start':
        start_layout(p)
    elif page_id == 'personas':
        persona_layout(p)
    elif page_id == 'skills':
        skills_layout(p)
    elif page_id == 'links':
        links_layout(p)
    elif page_id == 'equip':
        equip_layout(p)
    elif page_id == 'items':
        items_layout(p)
    elif page_id == 'stats':
        status_layout(p)
    elif page_id == 'calendar':
        calendar_layout(p)
    elif page_id == 'map':
        map_layout(p)
    elif page_id == 'talk':
        talk_layout(p)

def apply(path=MANIFEST):
    data = json.loads(path.read_text(encoding='utf-8'))
    assert data.get('title_id') == '0100DCD01525A000', (
        'Thor UI preview requires the Persona 3 Portable manifest')
    assert (data.get('canvas_w'), data.get('canvas_h')) == (1240, 1080), (
        'Unexpected P3P canvas dimensions')
    # Re-running the optional pass on an already generated preview must not
    # add overlays a second time or modify the source-derived widget order.
    if data.get('name') == PORT_NAME:
        return
    assert data.get('name') == 'Persona 3 Portable live companion', (
        'Regenerate the base manifest before applying this source preview')
    original = copy.deepcopy(data)
    assert len(data['pages']) == 12 and len(data['module_outputs']) == 2798
    pages = {p['id']: p for p in data['pages']}
    main_menu(pages['home'])
    battle(pages['battle'])
    for page in data['pages']:
        if page['id'] not in ('home', 'battle'):
            normalize_other_pages(page)
    data['name'] = PORT_NAME
    for key in ('module_outputs','module','actions','page_binds','enforce','enforce_gate'):
        assert data[key] == original[key], 'Unexpected change to '+key
    assert len(data['pages']) == len(original['pages'])
    assert not any(w.get('src','').startswith('file:img/')
                   for p in data['pages'] for w in p['widgets'])
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False)+'\n',
                    encoding='utf-8')


if __name__ == '__main__':
    apply()

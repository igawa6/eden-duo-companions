def normalize_other_pages(p):
    page_id = p['id']
    rules = READABILITY.get(page_id, {})
    for w in p['widgets']:
        if w.get('type') != 'label':
            if w.get('type') == 'button' and w.get('text') == 'Back':
                w['text_scale'] = 6
            continue

        bind = w.get('bind_text', '')
        if bind in rules:
            w.update(rules[bind])

        if bind == 'live.date':
            w['text_scale'] = 5

        # The longer strings are game-driven; fixed-size labels clip them.
        # Keep their text in the existing visual lane, with a safe lower scale.
        dynamic = (
            bind.endswith(('.name', '.help', '.partner', '.people'))
            or bind in rules
            or bind.startswith('choice.') and bind.endswith('.text')
        )
        rect = w.get('rect', [0, 0, 0, 0])
        if dynamic and rect[2] > 0:
            w['fit_text'] = True
            w['wrap_width'] = rect[2]
            w.setdefault('text_min_scale', 3)
            w.setdefault('max_lines', 1)

    if page_id == 'personas':
        persona_layout(p)
    elif page_id == 'skills':
        skills_layout(p)
    elif page_id == 'links':
        links_layout(p)
    elif page_id == 'equip':
        equip_layout(p)
    elif page_id == 'items':
        items_layout(p)

def apply(path=MANIFEST):
    data = json.loads(path.read_text(encoding='utf-8'))
    original = copy.deepcopy(data)
    assert len(data['pages']) == 12 and len(data['module_outputs']) == 2798
    pages = {p['id']: p for p in data['pages']}
    main_menu(pages['home'])
    battle(pages['battle'])
    for page in data['pages']:
        if page['id'] not in ('home', 'battle'):
            normalize_other_pages(page)
    data['name'] = 'Persona 3 Portable live companion — Thor UI source preview'
    for key in ('module_outputs','module','actions','page_binds','enforce','enforce_gate'):
        assert data[key] == original[key], 'Unexpected change to '+key
    assert len(data['pages']) == len(original['pages'])
    assert not any(w.get('src','').startswith('file:img/')
                   for p in data['pages'] for w in p['widgets'])
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False)+'\n',
                    encoding='utf-8')


if __name__ == '__main__':
    apply()

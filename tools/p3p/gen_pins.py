#!/usr/bin/env python3
"""Regenerate code fingerprints from the user's supported main NSO."""
import argparse
from pathlib import Path
from nso import decode
from saves import BUILD
RANGES = [(0x1d0940,20),(0x1d2d00,32),(0x1e7c90,20),(0x16a8f0,12),
          (0xf9df0,0x880),(0x1d0a80,48),(0x6e740,0x850),(0x1d0c50,68),
          (0x1d1460,0x100),(0x1d7310,0x110),(0x1d3e60,0xa0),(0x15fb90,0x54),
          (0x74a10,0x1cc),(0x6eb30,0x1a0),(0x77570,0x90),
          (0x1d3bf0,0x24),(0x1d3c20,0x180),(0x1ddff0,0x60)]
def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('nso',type=Path);a=p.parse_args()
    image,report=decode(a.nso)
    if report['build_id']!=BUILD:p.error('unsupported main build')
    text='// Build-specific FNV-1a code fingerprints; generated by tools/p3p/gen_pins.py.\nconstexpr Pin Pins[] = {\n'
    for at,n in RANGES:
        h=14695981039346656037
        for byte in image[at:at+n]:h=((h^byte)*1099511628211)&((1<<64)-1)
        text+=f'    {{0x{at:x}, 0x{n:x}, UINT64_C(0x{h:016x})}},\n'
    text+='};\n'
    (Path(__file__).resolve().parents[2]/'native/modules/p3p_pins.inc').write_text(text)
if __name__=='__main__':main()

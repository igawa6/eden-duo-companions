"""Index unconditional destructible obstacles from the supported v524288 romfs.

Only scene IDs, interactable IDs and native InteractableType numbers are emitted (no art or
localized display text). The live reader additionally requires a visited current room and
excludes IDs in MinimapEntry.InteractableActivated. Conditional or inactive objects are omitted.
Usage: python build_obstacle_catalog.py ROMFS [OUT]
"""
import json
import struct
import sys
from pathlib import Path

import UnityPy


class Reader:
    def __init__(self, data):
        self.data, self.at = data, 0

    def skip(self, size):
        self.at += size
        assert self.at <= len(self.data)

    def integer(self):
        value = struct.unpack_from('<i', self.data, self.at)[0]
        self.skip(4)
        return value

    def string(self):
        size = self.integer()
        assert 0 <= size <= 4096
        value = self.data[self.at:self.at + size].decode('utf8')
        self.skip(size)
        self.at = (self.at + 3) & ~3
        return value

    def header(self):
        self.skip(28)  # MonoBehaviour: GameObject PPtr, enabled, Script PPtr
        self.string()


def main():
    root = Path(sys.argv[1])
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[2] / 'native/modules/ms_obstacle_catalog.inc'
    env = UnityPy.load(str(root / 'Data/data.unity3d'))
    files = {obj.assets_file.name: obj.assets_file for obj in env.objects}
    scripts = {}

    def class_name(obj):
        file_id, path_id = struct.unpack_from('<iq', obj.get_raw_data(), 16)
        name = obj.assets_file.externals[file_id - 1].path.split('/')[-1] if file_id else obj.assets_file.name
        key = name, path_id
        if key not in scripts:
            scripts[key] = files[name].objects[path_id].read().m_ClassName
        return scripts[key]

    def active(obj):
        # Respect disabled parents too, rather than treating editor-only obstacles as live.
        go_id = struct.unpack_from('<q', obj.get_raw_data(), 4)[0]
        for _ in range(64):
            go = obj.assets_file.objects[go_id].read()
            if not go.m_IsActive:
                return False
            transform = next(obj.assets_file.objects[c.component.m_PathID] for c in go.m_Component
                             if c.component.m_FileID == 0 and obj.assets_file.objects[c.component.m_PathID].type.name == 'Transform').read()
            if not transform.m_Father.m_PathID:
                return True
            assert transform.m_Father.m_FileID == 0
            parent = obj.assets_file.objects[transform.m_Father.m_PathID].read()
            assert parent.m_GameObject.m_FileID == 0
            go_id = parent.m_GameObject.m_PathID
        raise ValueError('transform hierarchy exceeds bound')

    scenes, obstacles, ambiguous = {}, [], set()
    for obj in env.objects:
        if not obj.assets_file.name.startswith('level') or obj.type.name != 'MonoBehaviour':
            continue
        cls = class_name(obj)
        if cls not in ('MapSettings', 'Obstacle', 'ObstacleTendrils', 'ObstacleTileWall'):
            continue
        r = Reader(obj.get_raw_data())
        r.header()
        if cls == 'MapSettings':
            r.skip(24 + 8 + 12)  # BGM/volume/flags; inline MapData.Position and MapArea PPtr
            for _ in range(r.integer()):
                r.string()  # MapIconData.IconName
                r.skip(8)
                r.string()  # MapIconData.DisplayName
            r.skip(4 + 8 + 8)  # IsIndoor, FixedPlayerPosition, Size
            scene = r.string()
            if obj.assets_file.name in scenes and scenes[obj.assets_file.name] != scene:
                ambiguous.add(obj.assets_file.name)
            scenes[obj.assets_file.name] = scene
        else:
            iid, appear, disappear, kind = r.integer(), r.string(), r.string(), r.integer()
            r.skip(12)  # DestroyParticleEffect PPtr
            destroy = r.string()
            if iid >= 0 and 1 <= kind <= 12 and not (appear or disappear or destroy) and active(obj):
                obstacles.append((obj.assets_file.name, iid, kind))
    records = sorted({(scenes[file], iid, kind) for file, iid, kind in obstacles if file in scenes and file not in ambiguous})
    assert records and ('BlueCave_CentralPart', 10, 1) in records
    lines = ['// SPDX-FileCopyrightText: Copyright 2026 Eden DSMod fork',
             '// SPDX-License-Identifier: GPL-3.0-or-later',
             '// Generated by build_obstacle_catalog.py from v524288; native metadata only.']
    lines += [f'    {{{json.dumps(scene)}, {iid}, {kind}}},' for scene, iid, kind in records]
    output.write_text('\n'.join(lines) + '\n')
    print(f'{len(records)} unconditional obstacle records -> {output}')


if __name__ == '__main__':
    main()

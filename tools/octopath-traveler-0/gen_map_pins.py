#!/usr/bin/env python3
"""Pin map texture metadata from an owned 1.0.5 archive, without extracting artwork.

Decodes one member at a time in memory to pin decoded SHA1 and strict texture layout.
Only archive metadata/hashes are written. The optional reference Oodle library is a
local generation dependency, never a package input or runtime dependency.
"""
import argparse,ctypes,hashlib,json,struct
from pathlib import Path
from gen_pak_pins import texture_pin

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--members',required=True);p.add_argument('--pak',required=True)
p.add_argument('--oodle-library',required=True);p.add_argument('--out',required=True)
a=p.parse_args();entries=json.loads(Path(a.members).read_text())['members']
root='Octopath_Traveler0/Content/'
selected=sorted((path,e) for path,e in entries.items() if path.startswith(root+'UI/MiniMap/Texture/MAP/') and path.endswith('.uexp'))
assert 0<len(selected)<=2048
lib=ctypes.CDLL(a.oodle_library);dec=lib.OodleLZ_Decompress
dec.argtypes=[ctypes.c_void_p,ctypes.c_long,ctypes.c_void_p,ctypes.c_long,ctypes.c_int,ctypes.c_int,ctypes.c_int,ctypes.c_void_p,ctypes.c_long,ctypes.c_void_p,ctypes.c_void_p,ctypes.c_void_p,ctypes.c_long,ctypes.c_int];dec.restype=ctypes.c_long
lines=['// Generated by gen_map_pins.py; metadata only, no game pixels or keys.'];rows=[]
def digest(d):return '{'+','.join(str(b) for b in d)+'}'
with Path(a.pak).open('rb') as pak:
 assert Path(a.pak).stat().st_size==1594117919, 'Wrong merged archive size'
 for i,(path,e) in enumerate(selected):
  assert not e['encrypted'] and e['compression'] in (0,1) and 0<e['size']<=16*1024*1024,path
  assert 0<=e['offset']<1594117919 and 53<=e['header_bytes']<=65536
  assert e['header_bytes']<=1594117919-e['offset']
  pak.seek(e['offset']);header=pak.read(e['header_bytes'])
  assert len(header)==e['header_bytes'] and struct.unpack_from('<QQQI',header)==(0,e['compressed_size'],e['size'],e['compression'])
  blocksize=struct.unpack_from('<I',header,len(header)-4)[0]
  blocks=[tuple(b) for b in e['blocks']] if e['compression'] else []
  expected=e['block_size'] or (e['size'] if len(blocks)==1 else 0);assert blocksize==expected
  assert header[-5]==0, (path,'Encrypted/unknown entry flags')
  if e['compression']:
   assert 0<len(blocks)<=256 and len(header)==57+16*len(blocks)
   assert struct.unpack_from('<I',header,48)[0]==len(blocks)
   assert [struct.unpack_from('<QQ',header,52+16*k) for k in range(len(blocks))]==blocks
   assert blocks[0][0]==len(header)
   assert all(blocks[k][0]==blocks[k-1][1] for k in range(1,len(blocks)))
   assert blocks[-1][1]-blocks[0][0]==e['compressed_size']
   assert blocks[-1][1]<=1594117919-e['offset']
   assert blocksize>0 and (len(blocks)-1)*blocksize<e['size']<=len(blocks)*blocksize
  else:
   assert len(header)==53 and e['compressed_size']==e['size']
   assert e['size']<=1594117919-e['offset']-len(header)
  if blocks:
   compressed=[]
   for start,end in blocks:
    assert 0<end-start<=16*1024*1024
    pak.seek(e['offset']+start);b=pak.read(end-start);assert len(b)==end-start;compressed.append(b)
   stored=b''.join(compressed);assert len(stored)==e['compressed_size'] and hashlib.sha1(stored).digest()==header[28:48]
   decoded=bytearray()
   for b in compressed:
    n=min(blocksize,e['size']-len(decoded));buf=ctypes.create_string_buffer(n)
    assert dec(b,len(b),buf,n,1,0,0,None,0,None,None,None,0,3)==n,path
    decoded+=buf.raw
   data=bytes(decoded)
  else:
   pak.seek(e['offset']+e['header_bytes']);data=pak.read(e['size']);assert hashlib.sha1(data).digest()==header[28:48]
  assert len(data)==e['size']
  try:tex=texture_pin(data,path)
  except (AssertionError,struct.error,ValueError) as error:
   print('External/unsupported map mip omitted:',path, str(error));continue
  assert tex
  name=f'MapBlocks{i}'
  if blocks:lines.append(f'constexpr Block {name}[]={{'+','.join(f'{{{s},{t}}}' for s,t in blocks)+'};')
  member='{'+f'"{path[len(root):]}",{e["offset"]}ULL,{e["compressed_size"]},{e["size"]},{e["compression"]},{e["header_bytes"]},{blocksize},'+(name if blocks else '{}')+','+digest(header[28:48])+','+digest(hashlib.sha1(data).digest())+'}'
  texture='{'+f'TextureFormat::{tex["format"]},{tex["width"]},{tex["height"]},{tex["format_at"]},{tex["data_at"]},{tex["data_bytes"]}'+'}'
  rows.append('{'+member+','+texture+'},')
lines.append('constexpr MapTexturePin MapTexturePins[]={');lines+=rows;lines.append('};')
Path(a.out).write_text('\n'.join(lines)+'\n');print('Pinned',len(rows),'map textures; no decoded files written')

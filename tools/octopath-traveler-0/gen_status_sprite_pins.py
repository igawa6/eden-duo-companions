#!/usr/bin/env python3
"""Pin original native status PaperSprite imports/rectangles; never extract assets.

Only the bounded UI/Battle/Texture/Frames/UiTX_Battle_IconStatus_ family is
visited. Every member is <=1MiB and decoded individually in RAM, with stored
payload hashes verified before Oodle. Unsupported schemas abort generation.
"""
import argparse
import hashlib
import json
import math
import struct
from pathlib import Path
from gen_pak_pins import decode_uncached, texture_pin

ROOT = 'Octopath_Traveler0/Content/'
FAMILY = 'UI/Battle/Texture/Frames/UiTX_Battle_IconStatus_'


def package_import(data, source_index, object_name):
    assert len(data) < 1024 * 1024
    assert struct.unpack_from('<8i', data)[:2] == (-1641380927, -8)
    folder_n = struct.unpack_from('<i', data, 32)[0]
    assert 1 <= folder_n <= 512
    summary = 36 + folder_n
    count, offset = struct.unpack_from('<ii', data, summary + 4)
    import_count, import_offset = struct.unpack_from('<ii', data, summary + 36)
    assert 1 <= count <= 256 and 1 <= import_count <= 64
    names = []
    for _ in range(count):
        n = struct.unpack_from('<i', data, offset)[0]
        assert 1 <= n <= 512 and data[offset + 4 + n - 1] == 0
        names.append(data[offset + 4:offset + 4 + n - 1].decode('ascii'))
        offset += 4 + n + 4  # serialized FString plus two uint16 name hashes
    assert offset <= import_offset
    def fname(at):
        index, number = struct.unpack_from('<ii', data, at)
        assert 0 <= index < count and number == 0
        return names[index]
    def imp(index):
        assert -import_count <= index < 0
        at = import_offset + (-index - 1) * 32
        return fname(at), fname(at + 8), struct.unpack_from('<i', data, at + 16)[0], fname(at + 20)
    assert 'PaperSprite' in names and object_name in names
    _, cls, outer, name = imp(source_index)
    assert cls == 'Texture2D'
    _, outer_cls, grandparent, package = imp(outer)
    assert outer_cls == 'Package' and grandparent == 0
    assert package.startswith('/Game/UI/Battle/Texture/Textures/')
    assert package.rsplit('/', 1)[1] == name
    return package[6:] + '.uexp'


def checked_member(pak, entries, path, library):
    e = entries[path]
    assert not e['encrypted'] and e['compression'] in (0, 1)
    assert 0 < e['size'] <= 1024 * 1024
    assert 0 <= e['offset'] < 1594117919
    assert 53 <= e['header_bytes'] <= 65536
    pak.seek(e['offset'])
    h = pak.read(e['header_bytes'])
    blocks = [tuple(b) for b in e['blocks']] if e['compression'] else []
    assert len(h) == e['header_bytes'] == (57 + 16 * len(blocks) if blocks else 53)
    assert struct.unpack_from('<QQQI', h) == (0, e['compressed_size'], e['size'], e['compression'])
    assert h[-5] == 0
    block_size = struct.unpack_from('<I', h, len(h) - 4)[0]
    assert block_size == (e['block_size'] or (e['size'] if len(blocks) == 1 else 0))
    if blocks:
        assert 0 < len(blocks) <= 256 and block_size > 0
        assert struct.unpack_from('<I', h, 48)[0] == len(blocks)
        assert [struct.unpack_from('<QQ', h, 52 + 16 * i) for i in range(len(blocks))] == blocks
        assert all(0 < end - start <= 1024 * 1024 for start, end in blocks)
        assert blocks[-1][1] <= 1594117919 - e['offset']
        assert (len(blocks) - 1) * block_size < e['size'] <= len(blocks) * block_size
    else:
        assert e['compressed_size'] == e['size'] <= 1594117919 - e['offset'] - len(h)
    data = decode_uncached(pak, e, h, library)
    return data, e, h, block_size, blocks


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--members', required=True)
    p.add_argument('--pak', required=True)
    p.add_argument('--oodle-library', required=True)
    p.add_argument('--out', required=True)
    a = p.parse_args()
    entries = json.loads(Path(a.members).read_text())['members']
    selected = sorted(path for path in entries if path.startswith(ROOT + FAMILY) and path.endswith('.uexp'))
    assert 0 < len(selected) <= 512
    assert Path(a.pak).stat().st_size == 1594117919
    lines = ['// Generated by gen_status_sprite_pins.py; metadata only, no game assets/keys.']
    rows = []
    atlases = {}
    def digest(d):
        return '{' + ','.join('0x%02x' % b for b in d) + '}'
    def pin(result, symbol, path):
        data, e, h, block_size, blocks = result
        if blocks:
            lines.append('inline constexpr Block ' + symbol + '[]={' + ','.join('{%d,%d}' % b for b in blocks) + '};')
        return '{' + '"' + path[len(ROOT):] + '",' + f'{e["offset"]}ULL,{e["compressed_size"]},{e["size"]},{e["compression"]},{e["header_bytes"]},{block_size},' + (symbol if blocks else '{}') + ',' + digest(h[28:48]) + ',' + digest(hashlib.sha1(data).digest()) + '}'
    with Path(a.pak).open('rb') as pak:
        for i, path in enumerate(selected):
            export = checked_member(pak, entries, path, a.oodle_library)
            header = checked_member(pak, entries, path[:-5] + '.uasset', a.oodle_library)
            b = export[0]
            assert len(b) == 259 and b[:11] == bytes.fromhex('0000000001088204020301'), path
            assert b[-4:] == bytes.fromhex('c1832a9e')
            rect = struct.unpack_from('<4d', b, 11)
            assert all(math.isfinite(v) and v >= 0 and v == int(v) for v in rect)
            assert all(0 < v <= 1024 for v in rect[2:])
            source = struct.unpack_from('<i', b, 43)[0]
            name = path.rsplit('/', 1)[1][:-5]
            atlas = package_import(header[0], source, name)
            if atlas not in atlases:
                pixels = checked_member(pak, entries, ROOT + atlas, a.oodle_library)[0]
                texture = texture_pin(pixels, atlas)
                assert texture and texture['format'] == 'Bc3'
                atlases[atlas] = (texture['width'], texture['height'])
                del pixels
            width, height = atlases[atlas]
            x, y, w, h = rect
            assert x + w <= width and y + h <= height
            # Cooked six-vertex mesh independently confirms the source rectangle.
            assert struct.unpack_from('<i', b, 55)[0] == 6
            for vertex in range(6):
                u, v = struct.unpack_from('<2d', b, 75 + vertex * 32)
                assert u in (x / width, (x + w) / width)
                assert v in (y / height, (y + h) / height)
            object_path = '/Game/' + path[len(ROOT):-5] + '.' + name
            rows.append('{"' + object_path + '","' + atlas + '",{' + ','.join(str(int(v)) for v in rect) + '},' + pin(export, f'StatusSprite{i}Blocks', path) + ',' + pin(header, f'StatusSprite{i}HeaderBlocks', path[:-5] + '.uasset') + '},')
    lines += ['inline constexpr StatusSpritePin StatusSpritePins[]={'] + rows + ['};']
    Path(a.out).write_text('\n'.join(lines) + '\n')
    print(f'Pinned {len(rows)} status sprites; decoded assets never written')


if __name__ == '__main__':
    main()

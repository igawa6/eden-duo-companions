#!/usr/bin/env python3
"""Pin normal protagonist layer members without writing decoded game assets.

The user's merged archive and existing reference Oodle library are required. Every stored
member is SHA1 checked before decompression. One decoded member at a time is hashed and
its native texture schema validated; only offsets/hashes/layout metadata are emitted.
"""
import argparse, ctypes, hashlib, importlib.util, json, struct
from pathlib import Path


def main():
    p = argparse.ArgumentParser()
    for name in ['members', 'pak', 'oodle', 'out']:
        p.add_argument('--' + name, required=True)
    a = p.parse_args()
    spec = importlib.util.spec_from_file_location('base_pins', Path(__file__).with_name('gen_pak_pins.py'))
    base = importlib.util.module_from_spec(spec); spec.loader.exec_module(base)
    metadata = json.loads(Path(a.members).read_text())['members']
    selected = sorted((path, e) for path, e in metadata.items()
                      if '/Character/Resource/V1_0_0/Prt/' in path and path.endswith('_N.uexp'))
    assert len(selected) == 1038
    library = ctypes.CDLL(str(Path(a.oodle).resolve()))
    decode = library.OodleLZ_Decompress
    decode.argtypes = [ctypes.c_void_p, ctypes.c_long, ctypes.c_void_p, ctypes.c_long,
                       ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_void_p, ctypes.c_long,
                       ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_long, ctypes.c_int]
    decode.restype = ctypes.c_long
    out = ['// Generated by tools/octopath-traveler-0/gen_appearance_pins.py; do not edit.',
           '// Owned merged Switch 1.0.5 pak; metadata only, no decoded pixels.', '']
    rows = []
    hx = lambda b: '{' + ','.join(f'0x{x:02x}' for x in b) + '}'
    with Path(a.pak).open('rb') as pak:
        assert Path(a.pak).stat().st_size == 1594117919
        for index, (path, e) in enumerate(selected):
            assert not e['encrypted'] and e['compression'] == 1
            assert 0 < e['size'] < 1_000_000 and 0 < len(e['blocks']) <= 16
            pak.seek(e['offset']); header = pak.read(e['header_bytes'])
            assert struct.unpack_from('<QQQI', header) == (0,e['compressed_size'],e['size'],1)
            n = struct.unpack_from('<I', header, 48)[0]
            blocks = [tuple(pair) for pair in e['blocks']]
            assert n == len(blocks) and len(header) == 57 + 16*n
            assert header[-5] == 0 and struct.unpack_from('<I', header, len(header)-4)[0] == e['block_size']
            assert [struct.unpack_from('<QQ', header, 52+16*i) for i in range(n)] == blocks
            assert blocks[0][0] == len(header)
            assert all(blocks[i][0] == blocks[i-1][1] for i in range(1,n))
            assert blocks[-1][1] - blocks[0][0] == e['compressed_size']
            pak.seek(e['offset'] + blocks[0][0]); stored = pak.read(e['compressed_size'])
            stored_sha = hashlib.sha1(stored).digest()
            assert len(stored) == e['compressed_size'] and stored_sha == header[28:48]
            decoded = bytearray()
            for start, end in blocks:
                want = min(e['block_size'], e['size']-len(decoded))
                data = stored[start-blocks[0][0]:end-blocks[0][0]]
                target = ctypes.create_string_buffer(want)
                result = decode(data,len(data),target,want,1,0,0,None,0,None,None,None,0,3)
                assert result == want
                decoded.extend(target.raw)
            assert len(decoded) == e['size']
            texture = base.texture_pin(decoded,path)
            assert texture['format'] == 'Bgra8' and texture['width'] == 440 and texture['height'] <= 528
            block_name = f'AppearanceBlocks{index}'
            out.append(f'constexpr Block {block_name}[] = {{' + ','.join(f'{{{s},{t}}}' for s,t in blocks) + '};')
            relative = path.removeprefix(base.C)
            name = Path(relative).stem
            pin = (f'{{"{relative}",{e["offset"]}ULL,{e["compressed_size"]}ULL,{e["size"]}ULL,1,'
                   f'{e["header_bytes"]},{e["block_size"]},{block_name},{hx(stored_sha)},'
                   f'{hx(hashlib.sha1(decoded).digest())}}}')
            tex = (f'{{TextureFormat::Bgra8,{texture["width"]},{texture["height"]},'
                   f'{texture["format_at"]},{texture["data_at"]},{texture["data_bytes"]}}}')
            rows.append(f'    {{"{name}",{pin},{tex}}},')
    out.extend(['constexpr AppearancePin AppearancePins[] = {', *rows, '};', ''])
    Path(a.out).write_text('\n'.join(out))
    print(f'Pinned {len(rows)} normal-layer members, {Path(a.out).stat().st_size} source bytes; decoded assets not written.')

if __name__ == '__main__': main()

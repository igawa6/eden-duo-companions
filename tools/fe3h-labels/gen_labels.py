"""Makes the fixed words of the Fire Emblem: Three Houses companion follow the game's language.

Every `label` widget of the manifest with a fixed English `text` that has an entry in refs.py (a
game term) or own.py (the companion's own phrase) becomes a `bind_text` on "ui.l.<slug>"; the
module (fe3h_labels.h) publishes the words of the game's language under those keys. It also
applies layout_fix.py, which the wider words need.

It reads and rewrites the package manifest and writes the label table the module compiles in:

    python3 tools/fe3h-labels/gen_labels.py            # from the root of the repository

The manifest can be the one that is already converted: a label that has no fixed `text` any more is
left alone, and the table is written from the keys that the manifest binds. No game file is read.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
from layout_fix import fix_turn_overlap  # noqa: E402
from own import COLS, OWN, REFS_EXTRA  # noqa: E402
from refs import REFS  # noqa: E402

MANIFEST = os.path.join(ROOT, 'packages', 'FireEmblemThreeHouses', 'dualscreen', 'manifest.json')
TABLE = os.path.join(ROOT, 'native', 'modules', 'fe3h_labels_data.inc')
PREFIX = 'ui.l.'

# Fixed texts that stay as they are: the words of the states in which the module is not running
# (it cannot publish them), the name of the companion, and symbols.
STATIC = {'Waiting for the game', 'The Companion Module Did Not Start',
          'Supported Game VERSION: 1.2.0', 'Dual Screen Companion', '–', '→', '-'}

REFS_ALL = {k: v for k, v in REFS.items() if v}
REFS_ALL.update(REFS_EXTRA)


def slug(text):
    return re.sub(r'[^a-z0-9]+', '_', text.lower()).strip('_')


def lit(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    with open(MANIFEST, encoding='utf-8') as f:
        manifest = json.load(f)

    print('turn label / number layout:', fix_turn_overlap(manifest), 'widgets changed')

    used = []  # the English words that became keys, in order of appearance

    def walk(o):
        if isinstance(o, dict):
            if o.get('type') == 'label' and isinstance(o.get('text'), str) and 'bind_text' not in o:
                text = o['text']
                if text not in STATIC and (text in REFS_ALL or text in OWN):
                    if text not in used:
                        used.append(text)
                    o['bind_text'] = PREFIX + slug(text)
                    del o['text']
            for v in list(o.values()):
                walk(v)
        elif isinstance(o, list):
            for v in o:
                walk(v)

    for page in manifest['pages']:
        walk(page['widgets'])

    # the table: every key the manifest binds, whether it was converted now or before
    bound = set()

    def collect(o):
        if isinstance(o, dict):
            b = o.get('bind_text')
            if isinstance(b, str) and b.startswith(PREFIX):
                bound.add(b[len(PREFIX):])
            for v in o.values():
                collect(v)
        elif isinstance(o, list):
            for v in o:
                collect(v)

    for page in manifest['pages']:
        collect(page['widgets'])
    words = {slug(t): t for t in list(REFS_ALL) + list(OWN)}
    missing = sorted(bound - set(words))
    assert not missing, 'bound keys without a word: %s' % missing
    keys = sorted(bound, key=lambda k: words[k])
    assert len(set(keys)) == len(keys), 'slug collision'

    rows = []
    for key in keys:
        text = words[key]
        if text in REFS_ALL:
            part, index = REFS_ALL[text]
            own = [lit(text)] + ['nullptr'] * (len(COLS) - 1)
        else:
            part, index = -1, 0
            own = [lit(x) for x in OWN[text]]
            own[0] = lit(text)
        rows.append('    {%s, %d, %d, {%s}},' % (lit(key), part, index, ', '.join(own)))

    with open(TABLE, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// SPDX-FileCopyrightText: Copyright 2026 Eden_Duo_Mode contributors\n')
        f.write('// SPDX-License-Identifier: GPL-3.0-or-later\n')
        f.write('// Generated by tools/fe3h-labels/gen_labels.py: the labels the manifest binds.\n')
        f.write('// {key, game text part, game text index (part < 0: none), own text per column:\n')
        f.write('// en ja de fr es it ko twn chn}. A game text entry reads its word from the game\'s own\n')
        f.write('// message data in the game\'s language; its English text is the fallback. The other\n')
        f.write('// entries are the companion\'s own wording.\n')
        f.write('\n'.join(rows) + '\n')

    with open(MANIFEST, 'w', encoding='utf-8', newline='') as f:
        json.dump(manifest, f, ensure_ascii=False, separators=(',', ':'))
        f.write('\n')
    print('converted %d words; table of %d labels' % (len(used), len(rows)))


if __name__ == '__main__':
    main()

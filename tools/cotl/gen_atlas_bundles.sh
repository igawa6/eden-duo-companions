# Generates native/modules/cotl_atlas_bundles_1_5_27.inc: SpriteAtlas name to Addressables bundle (run in WSL).
# Takes about 2 min (reads the directories of all ~10,000 bundles).
set -euo pipefail
PROJ="$(cd "$(dirname "$0")/../.." && pwd)"
DEPS="${COTL_DEPS:-$HOME/cotl-deps}"
g++ -std=c++20 -O2 -I "$DEPS/eden-duo-companions/native/modules" -I "$DEPS/eden-duo/src" \
  "$PROJ/tools/cotl/bundlescan.cpp" -L"${BUILD_DIR:-$PROJ/build-mods}" -ldsmod-ce-unity-lib -o /tmp/cotl-bundlescan
{
  echo "// Generated by tools/cotl/gen_atlas_bundles.sh (Cult of the Lamb 1.5.27). Do not edit."
  /tmp/cotl-bundlescan "${COTL_ROMFS:?set COTL_ROMFS to the unpacked romfs}/Data/StreamingAssets/aa/Switch" |
    sed -n 's/^\(.*\.bundle\) atlas=\(.*\)$/COTL_ATLAS("\2", "\1")/p' | sort -u
} > "$PROJ/native/modules/cotl_atlas_bundles_1_5_27.inc"
grep -c COTL_ATLAS "$PROJ/native/modules/cotl_atlas_bundles_1_5_27.inc"

"""Generates native/modules/cotl_tarot_regions_1_5_27.inc: TarotCards.Card to the card front region.

  tarot_regions.py <skintable.txt> <card_skins.txt> > native/modules/cotl_tarot_regions_1_5_27.inc

skintable.txt: lines "<Card> <Name> \"<Skin>\"" (jump table of TarotCards.Skin, see
tools/cotl/README.md); card_skins.txt: output of spine_skins.py for WeaponCard.skel.
"""
import sys

skins = {}
for line in open(sys.argv[2], encoding="utf-8"):
    parts = line.rstrip("\n").split("\t")
    for p in parts[1:]:
        slot, rest = p.split(":", 1)
        if slot == "Card Front":
            skins[parts[0]] = rest.split("=", 1)[1]

print("// Generated by tools/cotl/tarot_regions.py (Cult of the Lamb 1.5.27). Do not edit.")
for line in open(sys.argv[1], encoding="utf-8"):
    card, name, skin = line.split(None, 2)
    skin = skin.strip().strip('"')
    if skin in skins:
        print(f'COTL_TAROT({card}, "{skins[skin]}") // {name}')

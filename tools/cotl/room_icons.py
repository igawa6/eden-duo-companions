"""Generates native/modules/cotl_room_icons_1_5_27.inc: room prefab (BiomeRoom.GameObjectPath) to MapIcon sprite.

  room_icons.py <roomicons.txt> <pidscan.txt> > native/modules/cotl_room_icons_1_5_27.inc

roomicons.txt: "<prefab path>\t<FileID>\t<PathID>\t..." (GenerateRoom.MapIcon per room prefab),
pidscan.txt: "<bundle>\t<PathID>\t<sprite name>" (sprites in the MapIcons bundle). See tools/cotl/README.md.
"""
import sys

names = {}
for line in open(sys.argv[2], encoding="utf-8"):
    b, pid, name = line.rstrip("\n").split("\t")
    names[pid] = name
rows = {}
for line in open(sys.argv[1], encoding="utf-8"):
    path, fid, pid, _ = line.rstrip("\n").split("\t")
    if pid in names:
        rows[path] = names[pid]
print("// Generated by tools/cotl/room_icons.py (Cult of the Lamb 1.5.27). Do not edit.")
for path in sorted(rows):
    print(f'COTL_ROOMICON("{path}", "{rows[path]}")')

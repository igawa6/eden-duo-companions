"""Reads the group lists of the inventory menu from the constructor Lamb.UI.InventoryMenu..ctor.

  menu_lists.py <exefs/main> <script.json> <out.inc>

The constructor builds _currencyFilter (+0x138), _foodSorter (+0x140) and _itemsSorter (+0x148) as
List<ITEM_TYPE> with a series of Add(<constant>) calls. Output: COTL_MENU(<group>, <type>)
in order, for native/modules/cotl_inventory_menu_1_5_27.inc.
"""
import io
import contextlib
import re
import sys

import disasm

FIELDS = {"0x138": "Currency", "0x140": "Food", "0x148": "Items"}


def main():
    image = disasm.load_nso(sys.argv[1])
    syms = disasm.load_symbols(sys.argv[2])
    start = next(a for a, n in syms.items() if n == "Lamb.UI.InventoryMenu$$.ctor")
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        disasm.disasm(image, syms, start, 20000)
    current, lists = [], {}
    pending = None
    for line in buf.getvalue().splitlines():
        if "List<Int32Enum>$$.ctor" in line:
            current = []
        m = re.search(r"mov\s+w1, #(0x[0-9a-f]+|\d+)\s", line)
        if m:
            pending = int(m.group(1), 0)
        if "List<Int32Enum>$$AddWithResize" in line and pending is not None:
            current.append(pending)
            pending = None
        m = re.search(r"str\s+x\d+, \[x19, #(0x1[34][08])\]", line)
        if m and m.group(1) in FIELDS:
            lists[FIELDS[m.group(1)]] = current
            current = []
    missing = [g for g in FIELDS.values() if g not in lists]
    if missing:
        sys.exit(f"Lists not found: {missing}")
    with open(sys.argv[3], "w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/cotl/menu_lists.py from InventoryMenu..ctor (1.5.27). Do not edit.\n")
        for group in FIELDS.values():
            for t in lists[group]:
                out.write(f"COTL_MENU({group}, {t})\n")
    print({g: len(v) for g, v in lists.items()})


if __name__ == "__main__":
    main()

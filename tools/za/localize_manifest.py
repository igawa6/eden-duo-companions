"""Bind companion captions to native, save-language text. Works on runtime19 too."""
import copy
import hashlib
import json
from pathlib import Path
from ui_i18n import FALLBACKS

def canonical(text):return ' '.join(text.split())
def cpp(text):return json.dumps(text,ensure_ascii=False)

def localize(pages,root):
    specs={}
    def point(source='',bind='',names=None,maximum='',separator=' / ',pad=0,count=1):
        spec=(canonical(source),bind,tuple(names or []),maximum,separator,pad,count)
        key='za.ui.'+hashlib.sha256(repr(spec).encode()).hexdigest()[:12]
        specs[key]=spec
        return key+('{i}' if '{i}' in bind else '')
    for page in pages:
        out=[]
        for original in page['widgets']:
            w=copy.deepcopy(original);kind=w.get('type');text=w.get('text','')
            if w.pop('_static',False):out.append(w);continue
            if kind in ('label','value','button'):
                w['text_scale']=max(5,w.get('text_scale',4));w['text_min_scale']=5
            if kind=='button' and text:
                caption={k:v for k,v in w.items() if k not in ('id','on_tap','on_hold','on_swipe_left','on_swipe_right','type','text','border','bg','nav','input_block')}
                inset=w.pop('_caption_inset',0)
                caption.pop('_caption_inset',None)
                x,y,width,height=w['rect'];text_h=caption['text_scale']*5
                caption.update(type='label',rect=[x+(width+inset)//2,y+(height-text_h)//2,0,text_h],align='center',bind_text=point(text),wrap_width=width-24-inset,max_lines=1,line_gap=1,fit_text=True)
                w['text']='';out.extend((w,caption));continue
            if kind=='label' and text and not w.get('bind_text'):
                w['bind_text']=point(text);w['text']=''
            if kind=='value' and w.get('table')=='natures':
                w.update(type='label',bind_text='za.boxdetail.nature_name',text='');w.pop('bind',None);w.pop('table',None)
            elif kind=='value' and (text or w.get('names')):
                count=w.get('repeat',1) if '{i}' in w.get('bind','') else 1
                translated=point(text,w.get('bind',''),w.get('names'),w.get('max_bind',''),w.get('max_sep',' / '),w.get('pad',0),count)
                for key in ('bind','names','pad','max_bind','max_sep'):w.pop(key,None)
                w.update(type='label',bind_text=translated,text='')
            out.append(w)
        page['widgets']=out
    lines=['// SPDX-FileCopyrightText: Copyright 2026 Sickops','// SPDX-License-Identifier: GPL-3.0-or-later','// Generated by gen_manifest.py. Do not edit.','#pragma once','#include <string>','#include <vector>','namespace za::ui {',
           'struct Phrase {const char* source;const char* text[12];};','inline const Phrase phrases[]={']
    for source,row in sorted(FALLBACKS.items()):
        lines.append('{'+cpp(source)+',{'+','.join(cpp(row.get(i,row[2])) for i in range(12))+'}},')
    lines += ['};','struct Spec {const char* point;const char* source;const char* bind;const char* maximum;const char* separator;int pad,count;std::vector<const char*> names;};','inline const Spec specs[]={']
    for key,(source,bind,names,maximum,separator,pad,count) in sorted(specs.items()):
        lines.append('{'+','.join(map(cpp,(key,source,bind,maximum,separator)))+f',{pad},{count},'+'{'+','.join(map(cpp,names))+'}},')
    lines += ['};','} // namespace za::ui','']
    (root/'native/modules/za_ui_catalog.h').write_text('\n'.join(lines),encoding='utf-8')
    (root/'tools/za/ui_bindings.generated.json').write_text(json.dumps(specs,ensure_ascii=False,indent=1),encoding='utf-8')

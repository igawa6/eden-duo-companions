"""Offline reference decoder for runtime encounter verification; output is never a build input.

SW_ROMFS_DIR=<player romfs> python3 tools/pokemon-sword/gen_route_encounters.py
    --variant sword --out <scratch reference header>
"""
import argparse
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import swsh_encounters as S  # noqa: E402
import sw_variants  # noqa: E402

TABLE_TO_LIVE = [0, 1, 2, 3, 6, 4, 5, 7, 8]
METHOD = {"wander": 0, "flying": 1, "surf": 2, "special": 3, "grass": 4, "trees": 5, "fishing": 6}
ALL = (1 << 9) - 1


def live_mask(table_weathers):
    m = 0
    for w in table_weathers:
        m |= 1 << TABLE_TO_LIVE[w]
    return m


def build(data):
    zones, slots = [], []
    for e in data.values():
        keyed = {}

        def add(sl, method, lo, hi, mask):
            k = (sl["species"], sl["form"], METHOD[method], sl["rate"], lo, hi)
            keyed[k] = keyed.get(k, 0) | mask

        for s in e.get("symbol", []):
            for g in s["weathers"]:
                for sl in g["slots"]:
                    add(sl, s["kind"], g["min"], g["max"], live_mask(g["weathers"]))
        for g in e.get("grass", []):
            for sl in g["slots"]:
                add(sl, "grass", g["min"], g["max"], live_mask(g["weathers"]))
        for m in ("trees", "fishing"):
            if m in e:
                for sl in e[m]["slots"]:
                    add(sl, m, e[m]["min"], e[m]["max"], ALL)
        first = len(slots)
        # grid order: method, then rate (desc); ties keep the table order
        for k, mask in sorted(keyed.items(), key=lambda kv: (kv[0][2], -kv[0][3])):
            slots.append((*k, mask))
        # Wild Area / Isle of Armor / Crown Tundra (every z_wr* zone, PKHeX EncounterArea8.IsWildArea):
        # wild Pokemon there are at least Lv. 60 once the player has entered the Hall of Fame
        # (PKHeX EncounterArea8 BoostLevel = 60). The module applies it with its champion flag.
        boost = 1 if e["zone"].startswith("z_wr") else 0
        zones.append((e["zone_hash"], first, len(slots) - first, live_mask(e["weathers_possible"]), boost, e["zone"]))
    return sorted(zones), slots


def render(zones, slots, variant):
    hidden, symbol = (t.removesuffix(".bin") for t in variant.encounter_tables)
    lines = [
        "// SPDX-FileCopyrightText: Copyright 2026 igawa6",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        f"// Generated by tools/pokemon-sword/gen_route_encounters.py from the romfs of {variant.name} {variant.build.version}",
        f"// (bin/archive/field/resident/data_table.gfpak {hidden} + {symbol}, placement.gfpak).",
        "// Do not edit. Ids and numbers only; names come from the game's message tables at run time.",
        "// Weather bits = the live weather enum (sw.location.weather.id), converted from the table order.",
        "#pragma once",
        "#include <array>",
        "#include <cstdint>",
        "namespace sw_route_encounters {",
        "enum Method : std::uint8_t { Wander = 0, Flying = 1, Surf = 2, Special = 3, Grass = 4, Tree = 5, Fishing = 6 };",
        "struct Slot { std::uint16_t species; std::uint8_t form, method, rate, min_level, max_level; std::uint16_t weathers; };",
        "struct Zone { std::uint64_t zone_hash; std::uint16_t first, count, weathers_possible; std::uint8_t boost60; };",
        "/// Post-game floor (PKHeX EncounterArea8.BoostLevel) of a boost60 zone once the game is beaten.",
        "inline constexpr int kBoostLevel = 60;",
        "/// Encounter sub-table index (0 Normal .. 8 Heavy Fog) -> live weather id; applied at bake time.",
        "inline constexpr std::array<int, 9> kTableToLive{" + ", ".join(map(str, TABLE_TO_LIVE)) + "};",
        f"inline constexpr Slot kSlots[{len(slots)}] = {{",
    ]
    for i in range(0, len(slots), 4):
        lines.append("    " + " ".join("{%d,%d,%d,%d,%d,%d,0x%03X}," % s for s in slots[i:i + 4]))
    lines += ["};", f"inline constexpr Zone kZones[{len(zones)}] = {{"]
    for zh, first, n, poss, boost, zid in zones:
        lines.append("    {0x%016Xull, %d, %d, 0x%03X, %d}, // %s" % (zh, first, n, poss, boost, zid))
    lines += ["};", "} // namespace sw_route_encounters", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed header differs")
    ap.add_argument("--out", required=True, help="scratch reference header (never a build input)")
    sw_variants.add_argument(ap)
    a = ap.parse_args()
    variant = sw_variants.get(a.variant)
    romfs = os.environ.get("SW_ROMFS_DIR", "")
    if not romfs or not (Path(romfs) / "bin/archive/field/resident/data_table.gfpak").exists():
        raise SystemExit(f"set SW_ROMFS_DIR to an extracted {variant.name} {variant.build.version} romfs")
    zones, slots = build(S.decode(romfs, variant.encounter_tables))
    text = render(zones, slots, variant)
    out = Path(a.out)
    if a.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{out} is out of date: rerun gen_route_encounters.py")
        print("up to date:", out)
        return
    out.write_text(text, encoding="utf-8")
    print("zones %d slots %d -> %s" % (len(zones), len(slots), out))


if __name__ == "__main__":
    main()

def capsule_room(cx0, cy0, cx1, cy1):
    """(glyph x, label x, label room) of a native command capsule: the glyph is 0.72 of the
    capsule height at the right end, the label starts at 0.36 h and never runs under the glyph."""
    h = cy1 - cy0
    gw = 160 * h * 0.72 / 120
    gx = cx1 - gw - h * 0.10
    lx = cx0 + h * .36
    return gx, lx, int(gx - lx - 8)


def stack_label_px(keys, room, sizes, tag):
    # keys: the stack's command keys (strings.json "cmd.<key>")
    """Owner 2026-11-01 ("use pokemon font size for fight, bag, and run text"): one label size for
    every capsule of a command stack, per language -- the largest of `sizes` at which ALL of that
    language's labels fit their room (room[key] px) unshrunk, so the stack never mixes sizes
    ("Pokémon" no longer drops a tier while Fight/Bag/Run keep theirs). Returns [(px, gate)]: one
    entry with gate None when every language shares a size, else one per size, gated on the
    companion language (@flag:lang)."""
    import text_fit
    groups = {}
    for i in range(len(lang_values("cmd.fight"))):    # + the stress build's pseudo-locale
        code = LANGS[i] if i < len(LANGS) else "en"
        texts = {k: lang_values(f"cmd.{k}")[i] for k in keys}
        px = next((p for p in sizes if all(text_fit.width(texts[k], TIER[p], code) <= room[k] for k in keys)),
                  sizes[-1])
        groups.setdefault(px, []).append(i)
    if len(groups) == 1:
        return [(next(iter(groups)), None)]
    out = []
    for px, langs in sorted(groups.items(), reverse=True):
        gate = f"d.cmdpx.{tag}.{px}"
        TAB_DERIVED[gate] = " || ".join(f"{LANG_FLAG} == {l}" for l in langs)
        out.append((px, gate))
    return out



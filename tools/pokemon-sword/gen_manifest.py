def build_sprite_map():
    # icon_stems_full.txt (gen_species_icon_table.py, from sw_species_icon_table.h's own
    # generated data) already covers every icon file sw_species_icons::Select() can ever
    # publish (every species' every form and gender look) -- no hand-maintained stem list. item_ids_full.txt (this
    # directory, see its own header) does the same for sw_item_icons::IconSource().
    m = {}
    for i in range(len(PERSONAL_TYPE_SLUGS)):
        m[type_src(i)] = type_src(i)
        # The module publishes the plate of the companion language (sw_lang.h ArtSuffix), and the
        # status badges (sw_status_icons.h) the same way.
        for suffix in ART_SUFFIXES:
            m[type_src(i, True, suffix)] = type_src(i, True, suffix)
    for slug in STATUS_SLUGS:
        for suffix in ART_SUFFIXES:
            m[status_src(slug, suffix)] = status_src(slug, suffix)
    stems = {s.strip() for s in STEMS.read_text().split() if s.strip()}
    for stem in sorted(stems):
        m[icon_pokemon_src(stem)] = icon_pokemon_src(stem)
    item_ids = {int(line) for line in ITEM_IDS.read_text().splitlines()
               if line.strip() and not line.strip().startswith("#")}
    for item_id in sorted(item_ids):
        m[item_icon_src(item_id)] = item_icon_src(item_id)
    # Den strip (sw_reader.h's SampleDens picks between these two by DenType -- both textures
    # confirmed present in this build's townmap_top_00.arc via tools/bntx_decode.py dump).
    for den_icon in ("townmap_icon_wr_00^q", "townmap_icon_dungeon_00^q"):
        src = arc("townmap", "townmap_top_00", den_icon)
        m[src] = src
    for i in range(1, 10):
        src = arc("townmap", "townmap_top_00", f"weather_icon_s_{i:02d}^t")
        m[src] = src
    # Route list: the Pokédex distribution page's weather icons (chips; 10 = the fishing glyph) and
    # box icons of encounter forms are module-owned runtime images.
    for i in range(1, 11):
        src = arc("pokedex", "pokedex_distribution", f"weather_icon_s_{i:02d}^t")
        m[src] = src
    return m




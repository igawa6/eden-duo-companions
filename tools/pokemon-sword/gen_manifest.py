def pseudo_text(key):
    """~140 % of the longest real translation (measured in the package font), with accented
    capitals so the cap/ascender room is exercised too. Format codes (%s, %d, %03d) are kept."""
    import text_fit
    longest = max((sw_strings.resolve(key, c, romfs()) for c in LATIN_LANGS), key=lambda t: text_fit.width(t, 5))
    if longest in UNTRANSLATED or not longest.strip():
        return longest
    target = text_fit.width(longest, 5) * 1.4
    pad = "ÀÉÎÕÜ àéîõü "
    out = longest
    i = 0
    while text_fit.width(out, 5) < target:
        out += pad[i % len(pad)]
        i += 1
    return out.rstrip()


def text_map(key):
    return {str(i): v for i, v in enumerate(lang_values(key))}


def english_key(text):
    """The key of a label written as "@key" or with its companion English literal."""
    if text.startswith("@"):
        assert text[1:] in STRINGS, text
        return text[1:]
    keys = [k for k, e in STRINGS.items() if e.get("en") == text and not k.startswith(MODULE_ONLY)]
    assert len(keys) == 1, (text, keys)
    return keys[0]


def _english_index():
    """English text -> key, for labels written with their English literal (companion text only: a
    game line is named "@key", its text is not in this repository). An English text that two keys
    translate differently is ambiguous: such a label must name its key (`lkey=`)."""
    by_en = {}
    for key, entry in STRINGS.items():
        if "en" in entry:
            by_en.setdefault(entry["en"], set()).add(key)
    return by_en


def localize_widgets(manifest):
    """Every label with literal text switches with the companion language (text_bind + text_map
    on d.lang, the companion language in effect; DrawLabel resolves it every frame, so a change on
    @settings shows at once).
    Images of the baked-text arcs (grptxt / grptext textures of an `_eng` arc) get the same
    choice as src_names. Returns the English literals with no strings.json key (a test failure)."""
    import re
    by_en = _english_index()
    missing, ambiguous = set(), set()
    baked = re.compile(r"^(romfs:/bin/appli/[^#]+?)_eng(\.arc#timg/__Combined\.bntx#grpte?xt_.*)$")

    def visit(w):
        if not isinstance(w, dict):
            return
        if w.get("type") == "label" and isinstance(w.get("text"), str):
            text = w["text"]
            key = w.pop("lkey", None)
            if text.startswith("@") and text[1:] in STRINGS:
                key = text[1:]
            if text.strip() and text not in UNTRANSLATED:
                if key is None:
                    keys = by_en.get(text, set())
                    # module-only word lists (egg groups, growth, evolution, types) never name a label
                    if len(keys) > 1:
                        keys = {k for k in keys if not k.startswith(MODULE_ONLY)} or keys
                    distinct = {tuple(lang_values(k)) for k in keys}
                    if not keys:
                        missing.add(text)
                    elif len(distinct) > 1:
                        ambiguous.add(text)
                    else:
                        key = sorted(keys)[0]
                if key is not None and sw_strings.is_game(key) and not PSEUDO:
                    # the game's line, published by the module in the companion language
                    assert text == "@" + key, (key, text)
                    del w["text"]
                    w["bind_text"] = GAME_KEY_PREFIX + key
                elif key is not None:
                    assert text in ("@" + key, STRINGS[key].get("en")), (key, text)
                    del w["text"]
                    w["text_bind"] = LANG_FLAG
                    w["text_map"] = text_map(key)
        if w.get("type") == "image" and isinstance(w.get("src"), str):
            m = baked.match(w["src"])
            if m and "bind" not in w:
                names = [m.group(1) + suffix + m.group(2) for suffix in ART_SUFFIXES]
                if PSEUDO:
                    names.append(names[2])  # the stress locale shows the German art
                w["bind"] = LANG_FLAG
                w["src_names"] = names
        for v in w.values():
            if isinstance(v, (dict, list)):
                walk(v)

    def walk(o):
        if isinstance(o, dict):
            visit(o)
        elif isinstance(o, list):
            for x in o:
                walk(x)

    walk(manifest["pages"])
    assert not ambiguous, f"ambiguous English label text, pass lkey=: {sorted(ambiguous)}"
    return sorted(missing)


def c_string(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 0x80:
            out.append(ch)
        else:
            out.append("".join(f"\\x{b:02X}" for b in ch.encode("utf-8")) + '""')
    return '"' + "".join(out) + '"'


def write_strings_header():
    """native/modules/sw_strings_data.h: the same table for the module (sw_strings.h S()). A game
    line is nullptr in kText (every language without the companion's own column) and its
    reference + English placeholder in kGame -- never its text. Both modules (Sword, Shield) share
    this header, so a variant's manifest-only row ("variant": its key) is left out."""
    keys = sorted(k for k in STRINGS if "variant" not in STRINGS[k])
    fix_bit = {name: 1 << i for i, name in enumerate(sw_strings.FIXES)}
    ident = lambda k: "k" + "".join(p[:1].upper() + p[1:] for p in k.replace("-", "_").replace(".", "_").split("_"))
    lines = [
        "// SPDX-FileCopyrightText: Copyright 2026 igawa6",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/pokemon-sword/gen_manifest.py from tools/pokemon-sword/strings.json",
        "// (companion text in every offered language; sources in that file). Do not edit.",
        "#pragma once",
        "namespace sw_str {",
        f"inline constexpr int kLangColumns = {len(LANGS)}; // " + ", ".join(LANGS),
        "enum class Id : int {",
    ]
    lines += [f"    {ident(k)}, // {k}" for k in keys]
    lines += ["    kCount,", "};",
              "inline constexpr const char* kKeys[static_cast<int>(Id::kCount)] = {"]
    lines += [f"    {c_string(k)}," for k in keys]
    lines += ["};", "// nullptr = the game's own line (kGame), read from the player's romfs at run time",
              "inline constexpr const char* kText[static_cast<int>(Id::kCount)][kLangColumns] = {"]
    for k in keys:
        cells = [c_string(STRINGS[k][c]) if sw_strings.authored(k, c) is not None else "nullptr" for c in LANGS]
        lines.append("    {" + ", ".join(cells) + "}, // " + k)
    lines += ["};", "// {dir, file, line, English placeholder, fix steps per language} of a game line",
              "inline constexpr GameRef kGame[static_cast<int>(Id::kCount)] = {"]
    for k in keys:
        if not sw_strings.is_game(k):
            lines.append("    {}, // " + k)
            continue
        dir_, file, line = sw_strings.game_ref(k)
        fix = [sum(fix_bit[f] for f in sw_strings.fixes(k, c)) for c in LANGS]
        lines.append(f'    {{"{dir_}", "{file}", {line}, {c_string(STRINGS[k]["fallback"])}, {{{{'
                     + ", ".join(str(f) for f in fix) + "}}}, // " + k)
    lines += ["};", "} // namespace sw_str", ""]
    text = "\n".join(lines)
    if not STRINGS_HEADER.exists() or STRINGS_HEADER.read_text(encoding="utf-8") != text:
        STRINGS_HEADER.write_text(text, encoding="utf-8")



def corners(x0, y0, x1, y1, r, color=WHITE):
    """inverse-corner masks: clip a square picture to a radius-r frame on a `color` ground."""
    s = f"file:img/cm{r}.png"
    return [image(x0, y0, r, r, s, tint=color), image(x1 - r, y0, r, r, s, tint=color, flip_x=True),
            image(x0, y1 - r, r, r, s, tint=color, flip_y=True),
            image(x1 - r, y1 - r, r, r, s, tint=color, flip_x=True, flip_y=True)]


def T(x, base, text="", px=34, color=INK, anchor="l", bind=None, maxw=None, **v):
    """mockup text(img, (x, base), text, px, anchor=anchor+'s', maxw=maxw)."""
    sc = TIER[px]
    d = {"type": "label", "rect": [round(x), round(base - 5 * sc), round(maxw or 0), 0],
         "text_scale": sc, "color": color, "align": {"l": "left", "m": "center", "r": "right"}[anchor]}
    if bind:
        d["bind_text"] = bind
    else:
        d["text"] = text
    if maxw:
        # kit.text's fit rule: shrink before ellipsis, one line
        d["wrap_width"] = round(maxw)
        d["max_lines"] = 1
        d["fit_text"] = True
        d["text_min_scale"] = max(4, sc - 1)
    return vis(d, **v)


def wrap2(w, top, height, min_scale=None):
    """Let a T() label take two lines instead of shrinking (longer translations), its one or two
    lines centred in the band [top, top + height] (text_center_h)."""
    w["rect"][1] = round(top)
    w["text_center_h"] = round(height)
    w["max_lines"] = 2
    w["text_min_scale"] = min_scale or w["text_scale"]
    return w


def V(x, base, bind, px=44, color=INK, anchor="l", suffix="", **v):
    """grouped number (value widget, group=true) at the mockup's text baseline."""
    sc = TIER[px]
    d = {"type": "value", "rect": [round(x), round(base - 5 * sc), 0, 0], "bind": bind, "group": True,
         "text_scale": sc, "color": color, "align": {"l": "left", "m": "center", "r": "right"}[anchor]}
    if suffix:
        d["suffix"] = suffix
    return vis(d, **v)


def V_lang(x, base, bind, px, color, anchor, suffix_key, need, tag):
    """A grouped number with a word after it ("12 caught"): value widgets have one fixed suffix,
    so there is one per language, each shown only while that language is chosen."""
    out = []
    for i, suffix in enumerate(lang_values(suffix_key)):
        gate = f"d.lang{i}.{tag}"
        TAB_DERIVED[gate] = f"({need}) && {LANG_FLAG} == {i}"
        out.append(V(x, base, bind, px, color, anchor, suffix=suffix, need=gate))
    return out


def disc(cx, cy, d, key, tkey=None, **v):
    """dir_a.type_disc(img, (cx, cy), t, d): circle of d filled with type_colour(t), the native
    typeIcon_NN ^t glyph texture at 0.72 d centred on it. Returns 2 widgets."""
    r, g = d // 2, round(d * 0.72)
    circle = image(cx - r, cy - r, d, d, f"file:img/rr{r}.png", slice_=[r, r, r, r], tint_bind=tkey or f"{key}_type", **v)

def page_binds():
    """Each automatic switch twice: a faded one and an instant one. A page_bind's transition is a
    parse-time literal, so Reduced motion picks the twin through its ready_bind, not its point:
    a twin whose ready gate opens re-arms with a silent baseline (mod_pages.cpp DrivePageBinds),
    so flipping the setting on the @settings page while the field state is already true never
    fires a switch. Only a real state edge does, on whichever twin is armed."""
    out = []
    for point, page_id, ms, ready in PAGE_BINDS:
        for kind, flag in (("fx", f"!{MOTION_FLAG}"), ("rm", MOTION_FLAG)):
            gate = f"d.pb.{kind}" + (".state" if ready else "")
            PAGE_BIND_DERIVED[gate] = f"{ready} && {flag}" if ready else flag
            target = {"page": page_id}
            if kind == "fx":
                target.update(transition="fade", duration_ms=ms)
            out.append({"point": point, "equals": 1, "when_equal": target, "ready_bind": gate})
    return out



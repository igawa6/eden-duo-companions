def tabgate(widgets, t):
    """Battle card tab t, shown only while the detail pane is (battle.pane_hidden off)."""
    # Template rows: one bound value carries both gates -- the tab index, pushed out of every
    # tab's keep range (+10) while the pane is hidden.
    TAB_DERIVED["d.bt.tabp"] = "sw.battle.tab + 10 * (@flag:battle.pane_hidden != 0)"
    for w in widgets:
        need = w.get("need_bind")
        if need and "{i}" in need and "hide_bind" not in w:
            # The runtime substitutes template keys, not standalone derived expressions.
            w.update(hide_bind="d.bt.tabp", keep_min=t, keep_max=t)
            continue
        if need:
            name = f"d.bt.t{t}.{need}"
            TAB_DERIVED[name] = f"sw.battle.tab == {t} && d.bt.pane && {need}"
        else:
            name = f"d.bt.t{t}"
            TAB_DERIVED[name] = f"sw.battle.tab == {t} && d.bt.pane"
        w["need_bind"] = name
    return widgets



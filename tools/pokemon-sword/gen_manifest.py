def scrolled(widgets, sid, dy=None):
    """Put card widgets into scroll region `sid`: each becomes a one-element repeat (the runtime
    scrolls/clips repeat clones only). `dy` = an extra y_bind offset (a derived px value) for
    widgets below a variable-height block; species sprites keep their own art y_bind."""
    for w in widgets:
        if "repeat" not in w:
            _SCROLL_IDS[0] += 1
            w.update(repeat=1, repeat_bind="", repeat_cols=1, repeat_dx=0, repeat_row_dy=0,
                     id=w.get("id", f"bt_sc{_SCROLL_IDS[0]}"))
        w["scroll"] = sid
        if dy and "y_bind" not in w:   # sprites keep their art offset; pre-offset rows keep theirs
            w["y_bind"], w["y_scale"] = dy, 1
    return widgets



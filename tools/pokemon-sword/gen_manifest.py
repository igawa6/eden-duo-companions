# ---------------------------------------------------------------------------------- primitives
def vis(d, need=None, hide=None, eq=None, kmin=None, kmax=None, dy=None, dx=None):
    if need:
        d["need_bind"] = need
    if hide:
        d["hide_bind"] = hide
        if eq is not None:
            d["hide_eq"] = eq
        if kmin is not None:
            d["keep_min"] = kmin
        if kmax is not None:
            d["keep_max"] = kmax
    if dy:
        d["y_bind"], d["y_scale"] = dy
    if dx:
        d["x_bind"] = dx
    return d


def rect(x, y, w, h, bg, **v):
    return vis({"type": "rect", "rect": [x, y, w, h], "bg": bg, "color": "#00000000", "frame": 0}, **v)


def bar(x, y, w, h, bind, max_bind, color, bg="#00000000", **v):
    """live-fraction fill bar (engine "bar" widget: bind/max_bind, fills left-to-right). Same
    primitive tools/luminescent-platinum/gen_manifest.py's hp_bar() already uses; no color_bind
    exists on this widget, so 3-tier HP colouring is 3 stacked bars, each need_bind-gated on one
    mutually-exclusive zone flag the reader publishes (.hpg/.hpy/.hpr)."""
    return vis({"type": "bar", "rect": [x, y, w, h], "bind": bind, "max_bind": max_bind,
                "color": color, "bg": bg, "frame": 0}, **v)


def image(x, y, w, h, src=None, tint=None, src_bind=None, tint_bind=None, slice_=None,
          src_rect=None, flip_x=False, flip_y=False, tint_colors=None, **v):
    d = {"type": "image", "rect": [round(x), round(y), round(w), round(h)], "empty_src": ""}
    if src_bind:
        d["src_bind"] = src_bind
    else:
        d["src"] = src
    if tint:
        d["tint"] = tint
    if tint_bind:
        d["tint_bind"] = tint_bind
        # TYPE_COLORS is the common case (every existing caller); a caller binding a different
        # int domain (e.g. the den strip's DenType) passes its own palette instead.
        d["tint_colors"] = tint_colors if tint_colors is not None else TYPE_COLORS
    if slice_:
        d["fill"] = "slice"
        d["slice"] = slice_
    if src_rect:
        d["src_rect"] = [round(c, 4) for c in src_rect]
    if flip_x:
        d["flip_x"] = True
    if flip_y:
        d["flip_y"] = True
    species_sprite_offset(d)
    return vis(d, **v)


# Pokemon box icons (136x112 textures) carry varying transparent padding. The reader publishes
# <prefix>.icon_dx/.icon_dy (icon pixels, sw_species_icon_metrics.h) that stand the art's feet on
# one baseline and centre it by its art; every species sprite is offset by them, scaled to its
# drawn size, so mons stand on their tray/pill consistently at every size.
SPECIES_ICON_PREFIXES = ("sw.party.", "sw.dex.", "sw.battle.own", "sw.battle.foe", "sw.battle.bench.",
                         "sw.battle.switch_suggest.", "sw.battle.raid.", "sw.route.", "sw.map.wild.strip.")


def species_sprite_offset(d):
    src = d.get("src_bind", "")
    # "<prefix>.icon_src" only (not item_icon_src / the route cards' micon_src method glyph)
    if not src.endswith(".icon_src"):
        return
    prefix = src[:-len("icon_src")]
    if not prefix.startswith(SPECIES_ICON_PREFIXES):
        return
    w, h = d["rect"][2], d["rect"][3]
    d["x_bind"], d["x_scale"] = prefix + "icon_dx", round(w / 136, 4)
    d["y_bind"], d["y_scale"] = prefix + "icon_dy", round(h / 112, 4)



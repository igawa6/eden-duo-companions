MOTION_FLAG = "@flag:motion.reduced"  # settings "Reduced motion" toggle (runtime 15 persisted flag)


ANIM_DERIVED = {}


def anim_group(widgets, point, group, ms=150, frm="fade", box_=None):
    """Attach one shared `anim` to every widget in `widgets` (built in place; returns `widgets`).

    rt22 ignores an `anim` without a `bind`, so every group gets a derived gate
    `d.anim.<group>` = `@flag:motion.reduced || <point>` (registered here, emitted by
    build_derived()). How that keeps Reduced motion correct (mod_pages.cpp UpdateGroupAnims,
    mod_ui.cpp WidgetHiddenHolding): a group animates only when its gate CHANGES while its page is
    showing. With Reduced motion on the gate is constantly 1, so nothing ever moves and each
    widget's own need/hide gate alone decides visibility. With it off the gate follows `point`,
    so the group fades/slides in the moment `point` turns true. Flag first: a missing `point`
    must not make the whole OR unknown (mod_expr.cpp: an unknown left operand is unknown).
    The 2026-10-26 attempt ANDed `!flag` into the gate instead, which closed (= hid) every open
    group when the flag turned on; OR never closes a group whose point is true.

    Each member therefore needs its own visibility gate equal to (or stricter than) `point`;
    a member with none gets `need_bind = point`. The group box is the union of its members'
    rects (mod_ui_widget_state.cpp AnimGroupBox) -- give `box_` when the members are unsized
    text or move with y_bind, so the redraw box covers every position the widgets can take.
    Repeat templates are refused: their clones would share one group key and one box."""
    gate = f"d.anim.{group}"
    expr = f"{MOTION_FLAG} || {point}"
    assert ANIM_DERIVED.get(gate, expr) == expr, f"anim group {group} reused with another point"
    assert " " not in point and "(" not in point, point
    ANIM_DERIVED[gate] = expr
    if box_ is None and any(str(w.get("y_bind", "")).endswith("icon_dy") for w in widgets):
        # Species sprites move by their art offset (|dx| <= 15, |dy| <= 8 icon px, scaled):
        # cover every position they can take.
        xs, ys, xe, ye = [], [], [], []
        for w in widgets:
            x, y, ww, hh = w["rect"]
            if w.get("type") == "label":  # unsized text: generous cover around its anchor
                ww = ww or 600
                x, y, ww, hh = x - ww, y - 80, 2 * ww, 110
            if ww <= 0 or hh <= 0:
                continue
            mx = 16 * w.get("x_scale", 0) if w.get("x_bind") else 0
            my = 8 * w.get("y_scale", 0) if w.get("y_bind") else 0
            xs.append(x - mx); ys.append(y - my); xe.append(x + ww + mx); ye.append(y + hh + my)
        if xs:
            box_ = [min(xs), min(ys), max(xe) - min(xs), max(ye) - min(ys)]
    for w in widgets:
        assert "repeat" not in w, f"anim on a repeat template ({group})"
        if "need_bind" not in w and "hide_bind" not in w:
            w["need_bind"] = point
        w["anim"] = {"bind": gate, "group": group, "from": frm, "ms": ms}
        if box_ is not None:
            w["anim"]["box"] = [round(c) for c in box_]
    return widgets


def repeated(w, n, count_bind, row_dy, id_, scroll_id, cols=1, dx=0):
    """Marks a widget as a repeat-template (PACKAGE_FORMAT.md section 3.5/3.6): `n` static
    instances, only `count_bind`'s live value actually shown, laid out `cols` wide (`dx` px
    apart) then `row_dy` px down per row, inside scroll region `scroll_id`. `id_`/any `{i}`-bearing
    string in `w` (bind/bind_text/src_bind/need_bind/hide_bind/payload/on_tap -- confirmed
    runtime-16+ substitution targets) is instantiated per index."""
    w["repeat"] = n
    w["repeat_bind"] = count_bind
    w["repeat_cols"] = cols
    w["repeat_dx"] = dx
    w["repeat_row_dy"] = row_dy
    w["id"] = id_
    w["scroll"] = scroll_id
    return w



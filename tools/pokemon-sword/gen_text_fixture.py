"""Generate native/modules/sw_game_text_fixture.inc (tests only): FNV-1a 64 hashes -- never the
text -- of what the module showed before F13 (2026-11-01) moved the game's own words to run time,
so sw_lang_test can prove, against the player's real romfs (SW_ROMFS_DIR), that the runtime
lookups give the same results as the baked tables they replaced:

  * kZoneNameHash[44][10]: the baked sw_zone_names.h table of the base commit (44 Wild Area zone
    names x 10 languages, sw_lang.h kFolders order);
  * kGameTextHash: per strings.json game row, the base commit's strings.json value in every
    language -- except where the row now shows the game's own wording instead of a near copy
    (CHANGED: English only, listed in the file), whose hash is today's resolved value.

    SW_ROMFS_DIR=<extracted romfs> python3 tools/pokemon-sword/gen_text_fixture.py [--base b92fe1b]
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sw_strings  # noqa: E402

ROOT = HERE.parents[1]
OUT = ROOT / "native/modules/sw_game_text_fixture.inc"


def fnv(text):
    h = 0xCBF29CE484222325
    for b in text.encode("utf-8"):
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def git_show(base, path):
    return subprocess.run(["git", "-C", str(ROOT), "show", f"{base}:{path}"], check=True, capture_output=True).stdout


def c_unescape(literal):
    """The text of one generated C string literal ("..." pieces with \\xHH escapes)."""
    raw = bytearray()
    for piece in re.findall(r'"((?:[^"\\]|\\.)*)"', literal):
        i = 0
        while i < len(piece):
            if piece[i] == "\\":
                if piece[i + 1] == "x":
                    raw.append(int(piece[i + 2:i + 4], 16))
                    i += 4
                    continue
                raw.extend({"n": b"\n", "\\": b"\\", '"': b'"'}[piece[i + 1]])
                i += 2
                continue
            raw.extend(piece[i].encode())
            i += 1
    return raw.decode("utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", default="b92fe1b", help="the commit with the baked tables")
    base = ap.parse_args().base
    romfs = sw_strings.Romfs()
    zones = []
    for row in re.findall(r"^    (\{.*\}), // (PLACENAME_\S+)$",
                          git_show(base, "native/modules/sw_zone_names.h").decode(), re.M):
        cells = re.findall(r'((?:"(?:[^"\\]|\\.)*")+)', row[0])
        assert len(cells) == 10, row[1]
        zones.append((row[1], [c_unescape(c) for c in cells]))
    assert len(zones) == 44
    old = json.loads(git_show(base, "tools/pokemon-sword/strings.json"))
    rows, changed = [], []
    for key in sorted(k for k in sw_strings.STRINGS if sw_strings.is_game(k)):
        hashes = []
        for lang in sw_strings.LANGS:
            now = sw_strings.resolve(key, lang, romfs)
            was = old[key][lang]
            if now != was:
                assert lang == "en", (key, lang, was, now)  # only English moved to the game's wording
                changed.append(f"{key} ({lang})")
            hashes.append(fnv(now))
        rows.append((key, hashes))
    out = [
        "// SPDX-FileCopyrightText: Copyright 2026 igawa6",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        f"// Generated by tools/pokemon-sword/gen_text_fixture.py (base {base}). Tests only: FNV-1a 64 of the",
        "// text the module showed before the game's words moved to run time (no text here). Do not edit.",
        "// Now the game's own wording instead of a near copy (English): " + ", ".join(changed) + ".",
        "#pragma once",
        "#include <cstdint>",
        "namespace sw_fixture {",
        "inline constexpr std::uint64_t kZoneNameHash[44][10] = {",
    ]
    out += ["    {" + ", ".join(f"0x{fnv(t):016X}ull" for t in names) + "}, // " + label for label, names in zones]
    out += ["};", "struct GameTextHash { const char* key; std::uint64_t hash[10]; };",
            f"inline constexpr GameTextHash kGameTextHash[{len(rows)}] = {{"]
    out += [f'    {{"{key}", {{' + ", ".join(f"0x{h:016X}ull" for h in hashes) + "}}," for key, hashes in rows]
    out += ["};", "} // namespace sw_fixture", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print("wrote", OUT, len(rows), "game rows,", len(changed), "changed:", changed)


if __name__ == "__main__":
    main()

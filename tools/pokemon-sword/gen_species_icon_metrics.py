"""Generate native/modules/sw_species_icon_metrics.h: the visible (alpha) bounding box of every
species' box icon, so sprites can stand on a common baseline and be centred by their art instead
of by the 136x112 texture (Sword's icons carry varying transparent padding).

Only numbers are emitted (no pixels). Reads the icon files sw_species_icon_table.h selects.

    SW_ROMFS_DIR=<extracted romfs dir> SW_BNTX_TOOLS=<dir with bntx_decode.py> \
        /tmp/g0venv/bin/python3 tools/pokemon-sword/gen_species_icon_metrics.py
"""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "native/modules/sw_species_icon_table.h"
OUT = ROOT / "native/modules/sw_species_icon_metrics.h"
ROMFS = Path(os.environ.get("SW_ROMFS_DIR", ""))
sys.path.insert(0, os.environ.get("SW_BNTX_TOOLS", ""))
import bntx_decode  # noqa: E402
from PIL import Image  # noqa: E402

ALPHA_MIN = 32  # BC1 punch-through alpha is 0/255; ignore any faint fringe anyway


def entries():
    text = TABLE.read_text()
    return [(int(s), int(i), int(f), c) for s, i, f, c in
            re.findall(r"\{(\d+), (\d+), (\d+), '([a-z])'\}", text)]


def bbox(path):
    blob = path.read_bytes()
    tex = next(iter(bntx_decode.iter_textures(blob)))
    w, h, px = bntx_decode.decode_texture(tex, blob)
    img = Image.frombytes("RGBA", (w, h), bytes(px))
    assert img.size == (136, 112), (path, img.size)
    alpha = img.getchannel("A").point(lambda a: 255 if a >= ALPHA_MIN else 0)
    return alpha.getbbox()  # (left, top, right_excl, bottom_excl)


def main():
    if not ROMFS.is_dir():
        sys.exit("set SW_ROMFS_DIR")
    rows = []
    for species, icon_id, form, suffix in entries():
        p = ROMFS / f"bin/appli/icon_pokemon/poke_icon_{icon_id:04d}_{form:02d}{suffix}_n.bntx"
        box = bbox(p)
        if not box:
            sys.exit(f"empty icon {p}")
        rows.append((species, *box))
    lines = [f"    {{{s}, {l}, {t}, {r}, {b}}}," for s, l, t, r, b in rows]
    OUT.write_text(f"""// SPDX-FileCopyrightText: Copyright 2026 igawa6
// SPDX-License-Identifier: GPL-3.0-or-later

// GENERATED by tools/pokemon-sword/gen_species_icon_metrics.py -- do not hand-edit.
//
// Visible (alpha >= {ALPHA_MIN}) bounding box of each species' 136x112 box icon (the exact file
// sw_species_icon_table.h selects), in icon pixels: left/top inclusive, right/bottom exclusive.
// Used to stand every sprite on one baseline and centre it by its art (OffsetFor below).

#pragma once

#include <cstdint>

namespace sw_species_icon_metrics {{

struct Box {{
    std::uint16_t species;
    std::uint8_t left, top, right, bottom;
}};

inline constexpr int kIconW = 136;
inline constexpr int kIconH = 112;
// Common baseline (exclusive bottom row of the art) and horizontal centre, icon pixels.
inline constexpr int kBaseline = 104;
inline constexpr int kCentreX = kIconW / 2;

inline constexpr Box kBoxes[]{{
{chr(10).join(lines)}
}};

/// Offset (icon pixels) that moves the art's feet onto kBaseline and its centre onto kCentreX.
/// Upward moves are limited so the art never leaves the texture's own top edge. False = no data.
inline bool OffsetFor(std::uint16_t species, int& dx, int& dy) {{
    for (const auto& b : kBoxes) {{
        if (b.species != species) continue;
        dy = kBaseline - b.bottom;
        if (dy < -static_cast<int>(b.top)) dy = -static_cast<int>(b.top);
        dx = kCentreX - (b.left + b.right) / 2;
        return true;
    }}
    return false;
}}

}} // namespace sw_species_icon_metrics
""")
    bottoms = sorted(r[4] for r in rows)
    print(f"{len(rows)} species; bottom min {bottoms[0]} median {bottoms[len(bottoms)//2]} max {bottoms[-1]}")


if __name__ == "__main__":
    main()

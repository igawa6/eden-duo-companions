"""Generate native/modules/sw_species_icon_metrics.h: the visible (alpha) bounding box of every
box icon file the module can show (each species' every form and gender look, sw_species_icon_table.h
kVariants), so sprites can stand on a common baseline and be centred by their art instead of by
the 136x112 texture (Sword's icons carry varying transparent padding; forms differ in size, e.g.
Galarian Darmanitan's Zen Mode).

Only numbers are emitted (no pixels). Reads the icon files sw_species_icon_table.h can select.

    SW_ROMFS_DIR=<extracted romfs dir> SW_BNTX_TOOLS=<dir with bntx_decode.py> \
        /tmp/g0venv/bin/python3 tools/pokemon-sword/gen_species_icon_metrics.py
"""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / "native/modules/sw_species_icon_table.h"
OUT = ROOT / "native/modules/sw_species_icon_metrics.h"
ROMFS = Path(os.environ.get("SW_ROMFS_DIR", ""))
sys.path.insert(0, os.environ.get("SW_BNTX_TOOLS", ""))
import bntx_decode  # noqa: E402
from PIL import Image  # noqa: E402

ALPHA_MIN = 32  # BC1 punch-through alpha is 0/255; ignore any faint fringe anyway


SUFFIX_BITS = (("m", 1), ("f", 2), ("s", 4), ("n", 8))


def stems():
    """Every (icon_id, form, suffix) of the table's kVariants, sorted."""
    text = TABLE.read_text()
    body = text.split("kVariants[]{", 1)[1].split("};", 1)[0]
    out = []
    for i, f, mask in re.findall(r"\{(\d+), (\d+), (\d+)\}", body):
        for suffix, bit in SUFFIX_BITS:
            if int(mask) & bit:
                out.append((int(i), int(f), suffix))
    return sorted(out)


def bbox(path):
    blob = path.read_bytes()
    tex = next(iter(bntx_decode.iter_textures(blob)))
    w, h, px = bntx_decode.decode_texture(tex, blob)
    img = Image.frombytes("RGBA", (w, h), bytes(px))
    assert img.size == (136, 112), (path, img.size)
    alpha = img.getchannel("A").point(lambda a: 255 if a >= ALPHA_MIN else 0)
    return alpha.getbbox()  # (left, top, right_excl, bottom_excl)


def main():
    if not ROMFS.is_dir():
        sys.exit("set SW_ROMFS_DIR")
    rows = []
    for icon_id, form, suffix in stems():
        p = ROMFS / f"bin/appli/icon_pokemon/poke_icon_{icon_id:04d}_{form:02d}{suffix}_n.bntx"
        box = bbox(p)
        if not box:
            sys.exit(f"empty icon {p}")
        rows.append((icon_id, form, suffix, *box))
    lines = [f"    {{{i}, {f}, '{c}', {l}, {t}, {r}, {b}}}," for i, f, c, l, t, r, b in rows]
    OUT.write_text(f"""// SPDX-FileCopyrightText: Copyright 2026 igawa6
// SPDX-License-Identifier: GPL-3.0-or-later

// GENERATED by tools/pokemon-sword/gen_species_icon_metrics.py -- do not hand-edit.
//
// Visible (alpha >= {ALPHA_MIN}) bounding box of every 136x112 box icon file the module can show
// (poke_icon_<icon_id>_<form><suffix>_n, sw_species_icon_table.h kVariants), in icon pixels:
// left/top inclusive, right/bottom exclusive. Sorted by (icon_id, form, suffix). Used to stand
// every sprite on one baseline and centre it by its art (OffsetFor below).

#pragma once

#include <cstdint>

namespace sw_species_icon_metrics {{

struct Box {{
    std::uint16_t icon_id;
    std::uint8_t form;
    char suffix;
    std::uint8_t left, top, right, bottom;
}};

inline constexpr int kIconW = 136;
inline constexpr int kIconH = 112;
// Common baseline (exclusive bottom row of the art) and horizontal centre, icon pixels.
inline constexpr int kBaseline = 104;
inline constexpr int kCentreX = kIconW / 2;

inline constexpr Box kBoxes[]{{
{chr(10).join(lines)}
}};

/// The art box of one icon file; nullptr = no data.
inline const Box* Find(std::uint16_t icon_id, std::uint8_t form, char suffix) {{
    for (const auto& b : kBoxes)
        if (b.icon_id == icon_id && b.form == form && b.suffix == suffix) return &b;
    return nullptr;
}}

/// Offset (icon pixels) that moves the art's feet onto kBaseline and its centre onto kCentreX.
/// Upward moves are limited so the art never leaves the texture's own top edge. False = no data.
inline bool OffsetFor(std::uint16_t icon_id, std::uint8_t form, char suffix, int& dx, int& dy) {{
    const Box* b = Find(icon_id, form, suffix);
    if (!b) return false;
    dy = kBaseline - b->bottom;
    if (dy < -static_cast<int>(b->top)) dy = -static_cast<int>(b->top);
    dx = kCentreX - (b->left + b->right) / 2;
    return true;
}}

}} // namespace sw_species_icon_metrics
""")
    bottoms = sorted(r[6] for r in rows)
    print(f"{len(rows)} icon files; bottom min {bottoms[0]} median {bottoms[len(bottoms)//2]} max {bottoms[-1]}")


if __name__ == "__main__":
    main()

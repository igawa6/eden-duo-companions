"""Generate native/modules/sw_variant_data.h from sw_variants.py (the module's variant records).

The structs are in sw_variant.h (hand-written); this writes their values, in declaration order
(C++20 designated initializers: a field out of order or missing does not compile).

    python3 tools/pokemon-sword/gen_variant_header.py [--check]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import sw_variants as V  # noqa: E402

ROOT = HERE.parents[1]
OUT = ROOT / "native/modules/sw_variant_data.h"


def c_bytes(hex_text: str, n: int) -> str:
    return "{" + ", ".join(f"0x{hex_text[2 * i:2 * i + 2]}" for i in range(n)) + "}"


def c_ident(key: str) -> str:
    return "k" + key[0].upper() + key[1:]


def render() -> str:
    lines = [
        "// SPDX-FileCopyrightText: Copyright 2026 igawa6",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/pokemon-sword/gen_variant_header.py from tools/pokemon-sword/sw_variants.py.",
        "// Do not edit: change sw_variants.py and regenerate. Structs: sw_variant.h (include that, not this).",
        "#pragma once",
        "namespace sw_variant {",
    ]
    for key, v in V.VARIANTS.items():
        b = v.build
        ident = c_ident(key)
        build_ident = f"{ident}{b.version.replace('.', '')}"
        lines.append(f"// {v.name} {b.version}, main {b.build_id[:40]}")
        lines.append(f"inline constexpr Build {build_ident}{{")
        lines.append(f"    {c_bytes(b.build_id, 20)},")
        lines.append(f'    "{b.build16}", "{b.version}", {b.image_span:#x},')
        lines.append("    MainOffsets{")
        for c_field, site_names in V.MODULE_MAIN_FIELDS:
            if isinstance(site_names, tuple):
                vals = ", ".join(f"{b.site(n).offset:#x}" for n in site_names)
                lines.append(f"        .{c_field} = {{{vals}}},")
            else:
                lines.append(f"        .{c_field} = {b.site(site_names).offset:#x},")
        lines.append("    }};")
        others = f"{ident}OtherBuilds"
        if v.other_builds:
            lines.append(f"inline constexpr KnownBuild {others}[{len(v.other_builds)}]{{")
            for id16, label in v.other_builds:
                lines.append(f'    {{{c_bytes(id16, 8)}, "{label}"}},')
            lines.append("};")
        else:
            others = "nullptr"  # no recognised-only build (a zero-length array is not C++)
        aoc = ", ".join(f"UINT64_C(0x{t:016X})" for t in v.aoc_title_ids)
        lines += [
            f"inline constexpr Variant {ident}{{",
            f"    UINT64_C(0x{v.title_id:016X}),",
            f'    "{v.name}",',
            f'    "{v.module_name}",',
            f"    {{{aoc}}},",
            f'    "{v.dex_comment_file}",',
            f"    {v.save_game_version},",
            f"    &{build_ident},",
            f"    {others},",
            f"    {len(v.other_builds)},",
            "};",
            f"#define SW_VARIANT_HAS_{key.upper()} 1",
        ]
    # Selection: SW_VARIANT_<KEY>=1 (CMake sw_add_variant_module) picks a non-default record.
    first = True
    for key, v in V.VARIANTS.items():
        if key == V.DEFAULT:
            continue
        lines.append(f"#{'if' if first else 'elif'} defined(SW_VARIANT_{key.upper()}) && SW_VARIANT_{key.upper()}")
        lines.append(f'#define SW_VARIANT_NAME "{v.name}"')
        lines.append(f'#define SW_VARIANT_ENCOUNTER_SUFFIX "{v.romfs_suffix}"')
        lines.append(f"inline constexpr const Variant& kActive = {c_ident(key)};")
        first = False
    d = V.VARIANTS[V.DEFAULT]
    if not first:
        lines.append("#else")
    lines.append(f"// Default variant: {d.name}.")
    lines.append(f'#define SW_VARIANT_NAME "{d.name}"')
    lines.append(f"// The variant's encounter archive member suffix.")
    lines.append(f'#define SW_VARIANT_ENCOUNTER_SUFFIX "{d.romfs_suffix}"')
    lines.append(f"inline constexpr const Variant& kActive = {c_ident(V.DEFAULT)};")
    if not first:
        lines.append("#endif")
    lines += ["} // namespace sw_variant", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the committed header differs")
    a = ap.parse_args()
    V.validate()
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{OUT} is out of date: rerun gen_variant_header.py")
        print("up to date:", OUT)
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())

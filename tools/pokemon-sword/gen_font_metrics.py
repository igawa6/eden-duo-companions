"""Generate native/modules/sw_font_metrics.h: the advance widths of the package font
(romfs:/bin/font/bmp/font_fs_72_00.bffnt, the manifest's "font") and the cap height the runtime
scales it by, so the module can publish where a label's text ends (the battle header's gender
mark sits right after the name, owner dev.23).

Mirrors the runtime exactly (src/core/mods/mod_nx_assets.cpp BuildBffntFont + mod_ui_text.cpp
Canvas::MeasureText): advance = CWDH char_width of the CMAP glyph (missing -> FINF alternate
glyph for cp >= 0x21), cap = baseline - first row of 'H' with alpha >= 128 (sheets bottom-up),
width(text, scale) = sum(advance) * scale * 5 / cap. Only numbers are emitted (no pixels).

    SW_ROMFS_DIR=<extracted romfs dir> SW_BNTX_TOOLS=<dir with bntx_decode.py> \
        python3 tools/pokemon-sword/gen_font_metrics.py
"""
import os
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "native/modules/sw_font_metrics.h"
ROMFS = Path(os.environ.get("SW_ROMFS_DIR", ""))
sys.path.insert(0, os.environ.get("SW_BNTX_TOOLS", ""))
import bntx_decode  # noqa: E402

FIRST, LAST = 0x20, 0x17F   # ASCII, Latin-1, Latin Extended-A (nicknames)
EXTRA = [0x2014, 0x2013, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x2642, 0x2640]


def main():
    d = (ROMFS / "bin/font/bmp/font_fs_72_00.bffnt").read_bytes()
    r16 = lambda o: struct.unpack_from("<H", d, o)[0]
    r32 = lambda o: struct.unpack_from("<I", d, o)[0]
    finf = r16(6)
    assert d[finf:finf + 4] == b"FINF"
    alter = r16(finf + 14)
    default_adv = d[finf + 18]
    t = r32(finf + 20) - 8
    cell_w, cell_h, baseline = d[t + 8], d[t + 9], r16(t + 16)
    cols, rows = r16(t + 20), r16(t + 22)
    sheet_off = r32(t + 28)
    widths, gwidths = {}, {}
    block = r32(finf + 24)
    while block >= 8:
        at = block - 8
        if d[at:at + 4] != b"CWDH":
            break
        first, last = r16(at + 8), r16(at + 10)
        for q, g in enumerate(range(first, last + 1)):
            e = at + 16 + q * 3
            widths[g] = d[e + 2]
            gwidths[g] = d[e + 1]
        nxt = r32(at + 12)
        block = nxt if nxt > block else 0
    cmap = {}
    block = r32(finf + 28)
    while block >= 8:
        at = block - 8
        if d[at:at + 4] != b"CMAP":
            break
        begin, end, method = r32(at + 8), r32(at + 12), r16(at + 16)
        q = at + 24
        if method == 0:
            base = r16(q)
            for c in range(begin, end + 1):
                cmap[c] = base + c - begin
        elif method == 1:
            for c in range(begin, end + 1):
                i = r16(q); q += 2
                if i != 0xFFFF:
                    cmap[c] = i
        elif method == 2:
            n = r16(q); q += 4
            for _ in range(n):
                i = r16(q + 4)
                if i != 0xFFFF:
                    cmap[r32(q)] = i
                q += 8
        nxt = r32(at + 20)
        block = nxt if nxt > block else 0

    blob = d[sheet_off:]
    tex = next(iter(bntx_decode.iter_textures(blob)))
    sw, sh, px = bntx_decode.decode_texture(tex, blob)
    per_sheet = cols * rows

    def alpha(x, y):  # upright atlas (sheet stored bottom-up), sheet 0 only
        return px[((sh - 1 - y) * sw + x) * 4 + 3]

    cap = 0
    for probe in "HEA":
        idx = cmap.get(ord(probe))
        if idx is None or idx >= per_sheet:
            continue
        cell = idx % per_sheet
        gx = (cell % cols) * (cell_w + 1) + 1
        gy = (cell // cols) * (cell_h + 1) + 1
        gw = gwidths.get(idx, d[finf + 17])
        for row in range(cell_h):
            if any(alpha(gx + col, gy + row) >= 128 for col in range(gw)):
                cap = baseline - row if row < baseline else 0
                break
        if cap:
            break
    assert cap, "no cap height"

    def adv(c):
        idx = cmap.get(c)
        if idx is None:
            if c < 0x21:
                return default_adv
            idx = alter
        return widths.get(idx, default_adv)

    table = [adv(c) for c in range(FIRST, LAST + 1)]
    covered = sorted(c for c in cmap if c >= 0x20)
    lines = [
        "// SPDX-FileCopyrightText: Copyright 2026 igawa6",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/pokemon-sword/gen_font_metrics.py from romfs:/bin/font/bmp/font_fs_72_00.bffnt",
        "// (the package font): CWDH advance widths and the cap height the runtime scales by. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "#include <atomic>",
        "#include <string_view>",
        "namespace sw_font {",
        f"inline constexpr int kCap = {cap};",
        f"inline constexpr char32_t kFirst = 0x{FIRST:X}, kLast = 0x{LAST:X};",
        f"inline constexpr int kAlterAdvance = {adv(0xFFFF)};",
        f"inline constexpr std::uint8_t kAdvance[{len(table)}] = {{",
    ]
    for i in range(0, len(table), 24):
        lines.append("    " + ",".join(str(v) for v in table[i:i + 24]) + ",")
    lines.append("};")
    lines.append("inline constexpr struct { char32_t cp; std::uint8_t adv; } kExtra[] = {")
    lines.append("    " + ", ".join(f"{{0x{c:X}, {adv(c)}}}" for c in EXTRA) + ",")
    lines.append("};")
    lines.append(f"// Every code point the font has a glyph for ({len(covered)}); others draw the alternate glyph.")
    lines.append(f"inline constexpr char32_t kCovered[{len(covered)}] = {{")
    for i in range(0, len(covered), 16):
        lines.append("    " + ",".join(f"0x{c:X}" for c in covered[i:i + 16]) + ",")
    lines.append("};")
    lines += [
        "// A module-built font in place of this table (sw_modfont.h: the Rodin face while the companion is",
        "// Japanese): what it covers, its advances in its own atlas px (-1 = none) and its cap height.",
        "struct Override {",
        "    bool (*covers)(char32_t);",
        "    int (*advance)(char32_t);",
        "    int (*cap)();",
        "};",
        "inline std::atomic<const Override*>& ActiveOverride() {",
        "    static std::atomic<const Override*> active{nullptr};",
        "    return active;",
        "}",
        "inline bool Covers(char32_t cp) {",
        "    if (const Override* o = ActiveOverride().load(std::memory_order_acquire)) return o->covers(cp);",
        "    std::size_t lo = 0, hi = sizeof kCovered / sizeof kCovered[0];",
        "    while (lo < hi) { const std::size_t mid = (lo + hi) / 2; if (kCovered[mid] < cp) lo = mid + 1; else hi = mid; }",
        "    return lo < sizeof kCovered / sizeof kCovered[0] && kCovered[lo] == cp;",
        "}",
        "// True when every code point of `utf8` has a real glyph (a nickname in another script would",
        "// draw as alternate glyphs: callers fall back to the species name).",
        "inline bool CoversText(std::string_view utf8) {",
        "    if (utf8.empty()) return false;",
        "    for (std::size_t i = 0; i < utf8.size();) {",
        "        const unsigned char c0 = static_cast<unsigned char>(utf8[i]);",
        "        char32_t cp = c0;",
        "        int n = c0 < 0x80 ? 1 : (c0 & 0xE0) == 0xC0 ? 2 : (c0 & 0xF0) == 0xE0 ? 3 : (c0 & 0xF8) == 0xF0 ? 4 : 1;",
        "        if (n > 1 && i + n <= utf8.size()) {",
        "            cp = c0 & (0x7F >> n);",
        "            for (int k = 1; k < n; ++k) cp = (cp << 6) | (static_cast<unsigned char>(utf8[i + k]) & 0x3F);",
        "        } else if (n > 1) return false;",
        "        i += n;",
        "        if (!Covers(cp)) return false;",
        "    }",
        "    return true;",
        "}",
        "inline int Advance(char32_t cp) {",
        "    if (const Override* o = ActiveOverride().load(std::memory_order_acquire)) {",
        "        const int a = o->advance(cp);",
        "        return a >= 0 ? a : (o->cap() + 1) / 2;",
        "    }",
        "    if (cp >= kFirst && cp <= kLast) return kAdvance[cp - kFirst];",
        "    for (const auto& e : kExtra) if (e.cp == cp) return e.adv;",
        "    return kAlterAdvance;",
        "}",
        "// Canvas::MeasureText for this font: width in canvas px of `utf8` at runtime text_scale `scale`.",
        "inline int MeasureText(std::string_view utf8, int scale) {",
        "    const Override* o = ActiveOverride().load(std::memory_order_acquire);",
        "    const int cap = o ? o->cap() : kCap;",
        "    long sum = 0;",
        "    for (std::size_t i = 0; i < utf8.size();) {",
        "        const unsigned char c0 = static_cast<unsigned char>(utf8[i]);",
        "        char32_t cp = c0;",
        "        int n = c0 < 0x80 ? 1 : (c0 & 0xE0) == 0xC0 ? 2 : (c0 & 0xF0) == 0xE0 ? 3 : (c0 & 0xF8) == 0xF0 ? 4 : 1;",
        "        if (n > 1 && i + n <= utf8.size()) {",
        "            cp = c0 & (0x7F >> n);",
        "            for (int k = 1; k < n; ++k) cp = (cp << 6) | (static_cast<unsigned char>(utf8[i + k]) & 0x3F);",
        "        } else n = 1;",
        "        i += n;",
        "        if (cp != '\\n') sum += Advance(cp);",
        "    }",
        "    return static_cast<int>(static_cast<float>(sum) * (static_cast<float>(scale) * 5.0f / static_cast<float>(cap)));",
        "}",
        "} // namespace sw_font",
    ]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"cap {cap}, wrote {OUT}")


if __name__ == "__main__":
    main()

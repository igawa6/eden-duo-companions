"""Generate native/modules/sw_zone_names.h: where sw_zone.h kZoneTable's 44 Wild Area zones have
their name in romfs bin/message/<Language>/script/place_name (the bare Town Map names, the same
line in every language folder). Line indices only (F13, 2026-11-01): the module reads the names
from the player's own romfs in every language (sw_reader.h EnsurePlaceLines), so the live
place-name popup, which is in the GAME's language, matches in any of them.

    SW_ROMFS_DIR=<extracted romfs dir> python3 tools/pokemon-sword/gen_zone_names.py
"""
import os
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "native/modules/sw_zone_names.h"
ROMFS = Path(os.environ.get("SW_ROMFS_DIR", ""))
FOLDERS = ["English", "French", "German", "Italian", "Spanish", "JPN_KANJI", "JPN", "Korean", "Simp_Chinese",
           "Trad_Chinese"]  # = sw_lang.h kFolders (the column is sw_lang::Index)
# kZoneTable order (sw_zone.h: Galar 0-16, Isle of Armor 17-31, Crown Tundra 32-43), by label.
ZONES = [f"PLACENAME_Z_WR{z}_01" for z in (
    "0102", "0103", "0104", "0105", "0106", "0107", "0108", "0109", "0110", "0121", "0122", "0131", "0132",
    "0133", "0134", "0135", "0136",
    "0201", "0202", "0203", "0204", "0205", "0206", "0207", "0208", "0209", "0211", "0221", "0222", "0223",
    "0224", "0231",
    "0301", "0303", "0304", "0305", "0306", "0308", "0309", "0310", "0312", "0313", "0321", "0323")]


def read_dat(path):
    """GameFreak text .dat (sw_text.h ReadDat): key 0x7C89 + 0x2983*line, rotl3 per unit. A
    control code becomes "\\0" (text_stress.py drops the rest of such a line)."""
    d = path.read_bytes()
    _, nlines, _, _, soff = struct.unpack_from("<HHIII", d, 0)
    out = []
    for i in range(nlines):
        off, ln, _ = struct.unpack_from("<IHH", d, soff + 4 + 8 * i)
        key = (0x7C89 + 0x2983 * i) & 0xFFFF
        s = []
        for j in range(ln):
            c = struct.unpack_from("<H", d, soff + off + 2 * j)[0] ^ key
            key = ((key << 3) | (key >> 13)) & 0xFFFF
            if c == 0:
                break
            s.append("\0" if c == 0x10 else chr(0xA0 if c == 0x202F else c))
        out.append("".join(s))
    return out


def read_tbl(path):
    d = path.read_bytes()
    n = struct.unpack_from("<I", d, 4)[0]
    off, out = 8, []
    for _ in range(n):
        ln = struct.unpack_from("<H", d, off + 8)[0]
        off += 10
        out.append(d[off:off + ln].rstrip(b"\0").decode())
        off += ln
    return out


def main():
    base = ROMFS / "bin/message"
    labels = read_tbl(base / "English/script/place_name.tbl")
    rows = []
    for label in ZONES:
        i = labels.index(label)
        for folder in FOLDERS:
            assert read_tbl(base / folder / "script/place_name.tbl")[i] == label, (folder, label)
            text = read_dat(base / folder / "script/place_name.dat")[i]
            assert "\0" not in text and text.strip(), (folder, label)
        rows.append((i, label))
    lines = [
        "// SPDX-FileCopyrightText: Copyright 2026 igawa6",
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/pokemon-sword/gen_zone_names.py from romfs bin/message/<Language>/script/",
        "// place_name.tbl (Sword 1.3.2): the line of each sw_zone.h kZoneTable zone's Town Map name, the same",
        "// in every language folder. Line indices only: the names are read from the player's romfs. Do not edit.",
        "#pragma once",
        "namespace sw_zone {",
        "inline constexpr int kZonePlaceLine[44] = {",
    ]
    lines += [f"    {i}, // {label}" for i, label in rows]
    lines += ["};", "} // namespace sw_zone", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()

"""Offline text measurement in the package font, mirroring the runtime exactly enough to find
crops/overflows without the emulator: advances from native/modules/sw_font_metrics.h (generated
from font_fs_72_00.bffnt, == Canvas::MeasureText), word wrap == Canvas::LayoutLines (break at
U+0020 only, a word wider than the line breaks by character, max_lines cuts with an ellipsis),
fit_text == DrawLabel's largest-fitting-scale search down to text_min_scale.

    width(text, scale) -> px          layout(text, scale, wrap, max_lines) -> [lines]
    fit(widget, text) -> (scale, lines, truncated, overflow_px)
"""
import re
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
METRICS = ROOT / "native/modules/sw_font_metrics.h"


@lru_cache(maxsize=None)
def _metrics():
    src = METRICS.read_text(encoding="utf-8")
    cap = int(re.search(r"kCap = (\d+);", src).group(1))
    first = int(re.search(r"kFirst = 0x([0-9A-Fa-f]+)", src).group(1), 16)
    alter = int(re.search(r"kAlterAdvance = (\d+);", src).group(1))
    adv = [int(x) for x in re.search(r"kAdvance\[\d+\] = \{(.*?)\};", src, re.S).group(1).replace("\n", "").split(",") if x.strip()]
    extra = {int(cp, 16): int(a) for cp, a in re.findall(r"\{0x([0-9A-Fa-f]+), (\d+)\}", src)}
    covered = {int(x, 16) for x in re.search(r"kCovered\[\d+\] = \{(.*?)\};", src, re.S).group(1).replace("\n", "").replace("0x", "").split(",") if x.strip()}
    return cap, first, alter, adv, extra, covered


# Japanese / Korean / Chinese (2026-11-01): the companion draws every glyph from the module's atlas
# (native/modules/sw_modfont.h): Japanese from the game's Rodin face, Korean / Chinese from the
# console's shared system fonts (Rodin only for what they lack). Their advances come from
# <code>_font_metrics.json (generated by native/modules/sw_modfont_tool.cpp, the module's own code;
# the Korean / Chinese ones from the real firmware 22.5.0 fonts). set_lang() picks the table width()
# and layout() measure with: a MODULE_LANGS code -> its table, anything else -> the package font.
HERE = Path(__file__).resolve().parent
JA_METRICS = HERE / "ja_font_metrics.json"
JA_LANGS = ("ja", "ja-kana")
CJK_LANGS = ("ko", "zh-Hans", "zh-Hant")
MODULE_LANGS = JA_LANGS + CJK_LANGS
# Chinese wraps between any two characters, Korean (like the Latin languages) at word spaces.
CHAR_BREAK_LANGS = JA_LANGS + ("zh-Hans", "zh-Hant")
LANG = "en"


def set_lang(code):
    """Measure with this language's font from now on; returns the previous code."""
    global LANG
    prev, LANG = LANG, code
    return prev


@lru_cache(maxsize=None)
def _module_metrics(code):
    import json
    name = "ja" if code in JA_LANGS else code
    d = json.loads((HERE / f"{name}_font_metrics.json").read_text(encoding="utf-8"))
    return d["cap"], {int(k, 16): v for k, v in d["advances"].items()}


def _ja_metrics():
    return _module_metrics("ja")


def module_covered(ch, code):
    """A glyph of a module-font language's face chain (the atlas the module would build)."""
    return ch in "\n " or ord(ch) in _module_metrics(code)[1]


def ja_covered(ch):
    return module_covered(ch, "ja")


def advance(ch):
    if LANG in MODULE_LANGS:
        cap, table = _module_metrics(LANG)
        return table.get(ord(ch), (cap + 1) // 2)
    cap, first, alter, adv, extra, covered = _metrics()
    cp = ord(ch)
    if first <= cp < first + len(adv):
        return adv[cp - first]
    return extra.get(cp, alter)


def covered(ch):
    if LANG in MODULE_LANGS:
        return module_covered(ch, LANG)
    return ord(ch) in _metrics()[5] or ch == "\n"


def width(text, scale, lang=None):
    if lang is not None:
        prev = set_lang(lang)
        try:
            return width(text, scale)
        finally:
            set_lang(prev)
    cap = _module_metrics(LANG)[0] if LANG in MODULE_LANGS else _metrics()[0]
    return int(sum(advance(c) for c in text if c != "\n") * scale * 5 / cap)


BROKEN = []  # words layout() had to split by character (a crop risk: "Schneeland|e")


def layout(text, scale, wrap=0, max_lines=0):
    lines = []
    for para in text.split("\n"):
        if wrap <= 0:
            lines.append(para)
            continue
        cur, has = "", False
        for word in para.split(" "):
            if has:
                cand = cur + " " + word
                if width(cand, scale) > wrap:
                    lines.append(cur)
                    cur, has = "", False
                else:
                    cur = cand
                    continue
            if width(word, scale) <= wrap:
                cur, has = word, True
            else:
                BROKEN.append(word)
                piece = ""
                for ch in word:
                    if piece and width(piece + ch, scale) > wrap:
                        lines.append(piece)
                        piece = ch
                    else:
                        piece += ch
                cur, has = piece, True
        lines.append(cur.rstrip(" "))
    truncated = False
    if max_lines > 0 and len(lines) > max_lines:
        truncated = True
        lines = lines[:max_lines]
        last = lines[-1].rstrip(" ")
        while last and wrap > 0 and width(last + "…", scale) > wrap:
            last = last[:-1].rstrip(" ")
        lines[-1] = last + "…"
    return lines, truncated


def fit(widget, text):
    """(scale, lines, truncated, overflow_px) of one label drawing `text`. overflow_px > 0: a
    single-line (no wrap_width) label wider than its rect width (when the rect has one)."""
    scale = widget.get("text_scale", 1)
    wrap = widget.get("wrap_width", 0)
    max_lines = widget.get("max_lines", 0)
    if widget.get("fit_text") and wrap > 0 and "\n" not in text:
        floor = max(1, min(widget.get("text_min_scale", 1), scale))
        while scale > floor and width(text, scale) > wrap:
            scale -= 1
    if wrap > 0 or "\n" in text:
        lines, truncated = layout(text, scale, wrap, max_lines)
    else:
        lines, truncated = [text], False
    rect_w = widget.get("rect", [0, 0, 0, 0])[2]
    widest = max((width(l, scale) for l in lines), default=0)
    limit = wrap or rect_w
    overflow = widest - limit if limit and widest > limit else 0
    return scale, lines, truncated, overflow

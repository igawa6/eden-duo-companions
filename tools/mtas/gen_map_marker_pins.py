"""Resolve native map sprite byte ranges; no artwork is copied into the package.

Requires UnityPy in the existing asset-tool environment. --scan is the tab-separated
(type, bundle-relative path, path ID, name) inventory from build_sprite_index.py.
"""
import argparse
import json
import struct
from pathlib import Path
import UnityPy

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--bundles', type=Path, required=True)
parser.add_argument('--scan', type=Path, required=True)
parser.add_argument('--output', type=Path, required=True)
parser.add_argument('--badges-output', type=Path)
args = parser.parse_args()
targets = {}
for line in args.scan.read_text().splitlines():
    fields = line.split('\t')
    if len(fields) == 4 and fields[0] == 'Sprite' and (fields[3].startswith(('I_Map_', 'I_Mission_icon_', 'I_Common_img_Arrow_')) or fields[3].endswith('_Mini') or fields[3] in ('I_Main_img_MapView_0', 'I_Button_btn_Reset_nor', 'button-green', 'I_Button_btn_Confirm01_nor', 'I_Reading_img_PageRight_00', 'I_Reading_img_PageLeft_00')):
        targets.setdefault(fields[3], (fields[1], int(fields[2])))
# The identical shared pin is already provided by MenuPins(), checked first.
targets.pop('I_Mission_icon_Other_00', None)
assert targets, 'no native map sprites in scan'
envs = {}
lines = ['// SPDX-FileCopyrightText: Copyright 2026 igawa6',
         '// SPDX-License-Identifier: GPL-3.0-or-later',
         '// Generated by tools/mtas/gen_map_marker_pins.py; byte ranges only, no pixels.', '{']
for name, (bundle, pid) in sorted(targets.items()):
    if bundle not in envs:
        envs[bundle] = UnityPy.load(str(args.bundles / bundle))
    data = next(o for o in envs[bundle].objects if o.path_id == pid).read()
    atlas = data.m_SpriteAtlas.read() if data.m_SpriteAtlas.path_id else None
    rd = dict(atlas.m_RenderDataMap)[data.m_RenderDataKey] if atlas else data.m_RD
    tex = rd.texture.read()
    fmt = int(tex.m_TextureFormat)
    assert fmt in (50, 51), (name, fmt)
    stream = tex.m_StreamData
    values = [stream.offset, tex.m_Width, tex.m_Height,
              1 << struct.unpack_from('<I', bytes(tex.m_PlatformBlob), 8)[0], 8 if fmt == 51 else 6]
    fields = [rd.textureRect.x, rd.textureRect.y, rd.textureRect.width, rd.textureRect.height,
              data.m_Border.x, data.m_Border.y, data.m_Border.z, data.m_Border.w]
    assert len(name.encode()) < 48
    prefix = ', '.join((json.dumps(name), '{' + json.dumps(bundle), json.dumps(stream.path.rsplit('/', 1)[-1])))
    numbers = ', '.join([str(values[0]) + 'ULL'] + [str(v) + 'u' for v in values[1:]] +
                        [str(round(float(v), 2)) + 'f' for v in fields])
    lines.append('    {' + prefix + ', ' + numbers + '}},')
lines.append('}')
args.output.write_text('\n'.join(lines) + '\n')
print(f'{len(targets)} native map sprites -> {args.output}')

if args.badges_output:
    sprite_names = {int(p[2]): p[3] for line in args.scan.read_text().splitlines()
                    if len(p := line.split('\t')) == 4 and p[0] == 'Sprite'}
    badges = []
    for bundle in sorted((args.bundles / 'uisystem_sprite').glob('mapicon_mission*')):
        env = UnityPy.load(str(bundle))
        root_name, badge = None, None
        for obj in env.objects:
            if obj.type.name == 'GameObject':
                name = obj.read().m_Name
                if name.startswith('MapIcon_'): root_name = name
            if obj.type.name != 'MonoBehaviour': continue
            raw = obj.get_raw_data()
            # Unity 2021 UI.Image: m_Sprite after Graphic/MaskableGraphic fields.
            if len(raw) != 136: continue
            go = struct.unpack_from('<iq', raw, 0)[1]
            if obj.assets_file.objects[go].read().m_Name != 'Image (1)': continue
            _, sprite = struct.unpack_from('<iq', raw, 88)
            badge = sprite_names.get(sprite)
        if root_name and badge: badges.append((root_name, badge))
    args.badges_output.write_text(
        '// SPDX-FileCopyrightText: Copyright 2026 igawa6\n'
        '// SPDX-License-Identifier: GPL-3.0-or-later\n'
        '// Native mission prefab Image (1).m_Sprite references; generated by gen_map_marker_pins.py.\n{\n' +
        ''.join('    {' + json.dumps(name) + ', ' + json.dumps(sprite) + '},\n' for name, sprite in badges) + '}\n')
